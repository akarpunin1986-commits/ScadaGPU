"""Seed knowledge base with structured content for Sanek AI assistant.

Usage:
    python -m app.scripts.seed_knowledge --api-url http://192.168.30.130:8010

This script generates structured knowledge chunks and uploads them
to the ScadaGPU knowledge base via the REST API.
"""
import argparse
import json
import sys
from io import BytesIO

import requests

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
DEFAULT_API_URL = "http://192.168.30.130:8010"


def upload_document(api_url: str, title: str, category: str, content: str, filename: str):
    """Upload a document to the knowledge base via API."""
    url = f"{api_url}/api/ai/knowledge/upload"
    files = {
        "file": (filename, BytesIO(content.encode("utf-8")), "text/plain"),
    }
    data = {
        "title": title,
        "category": category,
    }
    resp = requests.post(url, files=files, data=data, timeout=30)
    resp.raise_for_status()
    result = resp.json()
    print(f"  OK {title}: {result.get('chunks_stored', '?')} chunks")
    return result


