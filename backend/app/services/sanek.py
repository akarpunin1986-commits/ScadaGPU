async def _get_session_memory(site_id: int | None = None) -> str | None:
    """Load recent agent incidents from DB as context for LLM."""
    try:
        from models.base import async_session
        from models.agent_incident import AgentIncident
        from sqlalchemy import select, desc
        from datetime import datetime, timedelta

        # v4.0: no date limit — last 20 incidents for full context
        async with async_session() as db:
            q = (
                select(AgentIncident)
                .where(AgentIncident.status == "completed")
                .order_by(desc(AgentIncident.created_at))
                .limit(20)
            )
            if site_id:
                q = q.where(AgentIncident.site_id == site_id)
            rows = (await db.execute(q)).scalars().all()

        if not rows:
            return None

        lines = ["[ПАМЯТЬ: последние инциденты]"]
        for r in rows:
            ts = r.created_at.strftime("%d.%m %H:%M") if r.created_at else "?"
            cause = (r.cause or "")[:200]
            rec = (r.recommendation or "")[:150]
            lines.append(f"  {ts} device={r.device_id} {r.alarm_code}: {cause}")
            if rec:
                lines.append(f"    → {rec}")
        return "\n".join(lines)
    except Exception as e:
        logger.warning("Session memory load error: %s", e)
        return None


