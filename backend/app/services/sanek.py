async def _search_incidents_sql(query: str, device_id: int = None, limit: int = 5) -> dict:
    """Search historical incidents in PostgreSQL (full-text fallback)."""
    try:
        from models.base import async_session
        from models.agent_incident import AgentIncident
        from sqlalchemy import select, desc, or_

        async with async_session() as db:
            q = select(AgentIncident).where(AgentIncident.status == "completed")
            if device_id:
                q = q.where(AgentIncident.device_id == device_id)
            # Split query into keywords and search in cause + recommendation
            keywords = [w.strip() for w in query.split() if len(w.strip()) >= 2]
            if keywords:
                conditions = []
                for kw in keywords[:5]:
                    pat = f"%{kw}%"
                    conditions.append(AgentIncident.cause.ilike(pat))
                    conditions.append(AgentIncident.recommendation.ilike(pat))
                    conditions.append(AgentIncident.alarm_code.ilike(pat))
                q = q.where(or_(*conditions))
            q = q.order_by(desc(AgentIncident.created_at)).limit(limit)
            rows = (await db.execute(q)).scalars().all()

        if not rows:
            return {"found": 0, "incidents": [], "hint": "Похожих инцидентов в истории не найдено."}

        return {
            "found": len(rows),
            "incidents": [
                {
                    "date": r.created_at.strftime("%d.%m.%Y %H:%M") if r.created_at else "?",
                    "device_id": r.device_id,
                    "alarm_code": r.alarm_code or "",
                    "cause": (r.cause or "")[:300],
                    "recommendation": (r.recommendation or "")[:200],
                }
                for r in rows
            ],
        }
    except Exception as e:
        logger.warning("Incident history search error: %s", e)
        return {"found": 0, "error": str(e)}


