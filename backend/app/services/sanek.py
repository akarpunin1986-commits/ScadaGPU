    # OpenAI / Grok
    # ------------------------------------------------------------------
    async def _chat_openai(self, messages: list[dict], fast_only: bool = False, progress_queue: Optional[asyncio.Queue] = None) -> dict:
        from openai import AsyncOpenAI

        retried = False  # local flag to avoid cross-request leakage
        base_url = "https://api.x.ai/v1" if self.provider == "grok" else None
        client = AsyncOpenAI(
            api_key=self.api_key,
            timeout=self.timeout,
            base_url=base_url,
        )

        tools = _tools_for_openai(fast_only=fast_only)
        actions = []
        already_called = set()
        site_id = self._extract_site_id(messages)
        max_rounds = 5 if fast_only else 12
        max_tok = 2048 if fast_only else 8192

        for _ in range(max_rounds):
            # v3.2: Trim context to prevent overflow
            messages = _trim_context(messages, self.provider, self.model, max_tok)

            try:
                # GPT-5.x uses max_completion_tokens; older models use max_tokens
                token_param = "max_completion_tokens" if "gpt-5" in self.model else "max_tokens"
                response = await client.chat.completions.create(
                    model=self.model,
                    messages=messages,
                    tools=tools,
                    temperature=0.3,
                    **{token_param: max_tok},
                )
            except Exception as e:
                logger.error("OpenAI/Grok error: %s", e)
                return {"message": _format_llm_error(self.provider, e), "actions": actions, "pending_action": None}

            choice = response.choices[0]

            if choice.message.tool_calls:
                # Silent tools: execute without burning a round
                _SILENT = {"update_investigation"}
                all_silent = all(tc.function.name in _SILENT for tc in choice.message.tool_calls)
                if all_silent:
                    for tc in choice.message.tool_calls:
                        try:
                            _args = json.loads(tc.function.arguments) if tc.function.arguments else {}
                            await execute_tool(tc.function.name, _args)
                        except Exception:
                            pass
                    if (choice.message.content or "").strip():
                        return {"message": choice.message.content, "actions": actions, "pending_action": None}
                    # No text yet — add tool results and continue WITHOUT burning a round
                    messages.append(choice.message.model_dump())
                    for tc in choice.message.tool_calls:
                        messages.append({"role": "tool", "tool_call_id": tc.id, "content": "OK"})
                    continue

                messages.append(choice.message.model_dump())
                auto_followup_parts = []
                _auto_fu_count = 0  # v3.4 PERF: cap auto follow-ups

                for tc in choice.message.tool_calls:
                    tool_name = tc.function.name
                    tool_args = json.loads(tc.function.arguments) if tc.function.arguments else {}
                    logger.info("Tool call: %s(%s)", tool_name, tool_args)

                    if tool_name in DANGEROUS_TOOLS:
                        pending = self._build_pending_action(tool_name, tool_args)
                        return {"message": pending["description"], "actions": actions, "pending_action": pending}

                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "running"})
                    result = await execute_tool(tool_name, tool_args)
                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "done"})
                    already_called.add(tool_name)
                    summary = _summarize_tool_result(tool_name, result)
                    actions.append({"tool": tool_name, "args": tool_args, "result": result})
                    messages.append({"role": "tool", "tool_call_id": tc.id, "content": summary})

                    # v3.0: Collect auto follow-ups (skip in fast mode)
                    # v4.1 PERF: execute L1 follow-ups in PARALLEL
                    if _auto_fu_count < 3:
                        followups = await _detect_anomalies(tool_name, result, already_called, site_id or tool_args.get("site_id")) if not fast_only else []
                    else:
                        followups = []
                    # Cap to remaining budget
                    followups = followups[:max(0, 3 - _auto_fu_count)]
                    if followups:
                        if progress_queue:
                            for fu in followups:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "running", "auto": True})
                        # v4.1: parallel execution of independent follow-ups
                        fu_results = await asyncio.gather(
                            *[execute_tool(fu["name"], fu["args"]) for fu in followups],
                            return_exceptions=True,
                        )
                        for fu, fu_result in zip(followups, fu_results):
                            if isinstance(fu_result, Exception):
                                logger.warning("Auto follow-up %s failed: %s", fu["name"], fu_result)
                                continue
                            if progress_queue:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "done", "auto": True})
                            already_called.add(fu["name"])
                            fu_summary = _summarize_tool_result(fu["name"], fu_result)
                            actions.append({"tool": fu["name"], "args": fu["args"], "result": fu_result})
                            logger.info("Auto follow-up: %s — %s", fu["name"], fu["reason"])
                            auto_followup_parts.append(f"[Авто: {fu['name']}] {fu['reason']}\n{fu_summary}")
                            _auto_fu_count += 1

                # Inject auto follow-ups AFTER all tool responses (OpenAI requires tool responses first)
                if auto_followup_parts:
                    messages.append({"role": "user", "content": "[Система автоматически подгрузила дополнительные данные]\n\n" + "\n\n".join(auto_followup_parts)})

                continue

            text = choice.message.content or ""
            # v3.0: Validate and re-generate if fabrication detected (skip in fast mode)
            issues, correction = _validate_response(text, actions) if not fast_only else ([], None)
            if issues and not retried:
                retried = True
                logger.warning("Validation failed (%d issues), re-generating: %s", len(issues), "; ".join(issues))
                messages.append({"role": "assistant", "content": text})
                messages.append({"role": "user", "content":
                    "⚠ СТОП. Твой ответ содержит ошибки:\n" +
                    "\n".join(f"- {i}" for i in issues) +
                    "\n\nПерепиши ответ, исправив эти ошибки. Используй ТОЛЬКО данные из инструментов."
                })
                continue  # Re-generate
            if correction and not issues:
                text += correction
            return {"message": text, "actions": actions, "pending_action": None}

        return {"message": "Достигнут лимит вызовов инструментов.", "actions": actions, "pending_action": None}

    # ------------------------------------------------------------------
    # Claude (Anthropic)
    # ------------------------------------------------------------------
    async def _chat_claude(self, messages: list[dict], fast_only: bool = False, progress_queue: Optional[asyncio.Queue] = None) -> dict:
        tools = _tools_for_claude(fast_only=fast_only)
        actions = []
        already_called = set()
        retried = False  # local flag to avoid cross-request leakage
        site_id = self._extract_site_id(messages)

        system_text = ""
        chat_msgs = []
        for m in messages:
            if m["role"] == "system":
                system_text += m["content"] + "\n"
            else:
                chat_msgs.append(m)

        max_rounds = 5 if fast_only else 12
        max_tok = 2048 if fast_only else 8192

        for _ in range(max_rounds):
            # v3.2: Trim context to prevent overflow (system_text handled separately by Claude API)
            chat_msgs = _trim_context(chat_msgs, self.provider, self.model, max_tok)

            try:
                async with httpx.AsyncClient(timeout=self.timeout) as http:
                    body = {
                        "model": self.model,
                        "max_tokens": max_tok,
                        "system": system_text.strip(),
                        "messages": chat_msgs,
                        "tools": tools,
                        "temperature": 0.3,
                    }
                    resp = await http.post(
                        "https://api.anthropic.com/v1/messages",
                        headers={
                            "x-api-key": self.api_key,
                            "anthropic-version": "2023-06-01",
                            "content-type": "application/json",
                        },
                        json=body,
                    )
            except Exception as e:
                logger.error("Claude error: %s", e)
                return {"message": _format_llm_error("claude", e), "actions": actions, "pending_action": None}

            if resp.status_code != 200:
                try:
                    err = resp.json().get("error", {}).get("message", resp.text[:200])
                except Exception:
                    err = resp.text[:200]
                return {"message": _format_http_error("claude", resp.status_code, err), "actions": actions, "pending_action": None}

            data = resp.json()
            content_blocks = data.get("content", [])
            text_parts = []
            tool_uses = []
            for block in content_blocks:
                if block["type"] == "text":
                    text_parts.append(block["text"])
                elif block["type"] == "tool_use":
                    tool_uses.append(block)

            if tool_uses:
                # Silent tools: execute without burning a round
                _SILENT = {"update_investigation"}
                _text_combined = "\n".join(text_parts).strip()
                all_silent = all(tu["name"] in _SILENT for tu in tool_uses)
                if all_silent:
                    for tu in tool_uses:
                        try:
                            await execute_tool(tu["name"], tu.get("input", {}))
                        except Exception:
                            pass
                    if _text_combined:
                        return {"message": _text_combined, "actions": actions, "pending_action": None}
                    # No text yet — add tool results and continue WITHOUT burning a round
                    chat_msgs.append({"role": "assistant", "content": content_blocks})
                    tool_results_silent = [{"type": "tool_result", "tool_use_id": tu["id"], "content": "OK"} for tu in tool_uses]
                    chat_msgs.append({"role": "user", "content": tool_results_silent})
                    continue

                chat_msgs.append({"role": "assistant", "content": content_blocks})
                tool_results = []
                auto_msgs = []
                _auto_fu_count = 0  # v3.4 PERF: cap auto follow-ups

                for tu in tool_uses:
                    tool_name = tu["name"]
                    tool_args = tu.get("input", {})
                    logger.info("Claude tool call: %s(%s)", tool_name, tool_args)

                    if tool_name in DANGEROUS_TOOLS:
                        pending = self._build_pending_action(tool_name, tool_args)
                        text = "\n".join(text_parts) if text_parts else ""
                        return {"message": (text + "\n\n" + pending["description"]).strip(), "actions": actions, "pending_action": pending}

                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "running"})
                    result = await execute_tool(tool_name, tool_args)
                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "done"})
                    already_called.add(tool_name)
                    summary = _summarize_tool_result(tool_name, result)
                    actions.append({"tool": tool_name, "args": tool_args, "result": result})
                    tool_results.append({"type": "tool_result", "tool_use_id": tu["id"], "content": summary})

                    # v3.0: Auto follow-ups (skip in fast mode)
                    # v4.1 PERF: execute L1 follow-ups in PARALLEL
                    if _auto_fu_count < 3:
                        followups = await _detect_anomalies(tool_name, result, already_called, site_id or tool_args.get("site_id")) if not fast_only else []
                    else:
                        followups = []
                    followups = followups[:max(0, 3 - _auto_fu_count)]
                    if followups:
                        if progress_queue:
                            for fu in followups:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "running", "auto": True})
                        fu_results = await asyncio.gather(
                            *[execute_tool(fu["name"], fu["args"]) for fu in followups],
                            return_exceptions=True,
                        )
                        for fu, fu_result in zip(followups, fu_results):
                            if isinstance(fu_result, Exception):
                                logger.warning("Auto follow-up %s failed: %s", fu["name"], fu_result)
                                continue
                            if progress_queue:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "done", "auto": True})
                            already_called.add(fu["name"])
                            fu_summary = _summarize_tool_result(fu["name"], fu_result)
                            actions.append({"tool": fu["name"], "args": fu["args"], "result": fu_result})
                            logger.info("Auto follow-up: %s — %s", fu["name"], fu["reason"])
                            auto_msgs.append(f"[Авто: {fu['name']}] {fu['reason']}\n{fu_summary}")
                            _auto_fu_count += 1

                chat_msgs.append({"role": "user", "content": tool_results})
                if auto_msgs:
                    chat_msgs.append({"role": "user", "content": [{"type": "text", "text": "\n\n".join(auto_msgs)}]})
                continue

            text = "\n".join(text_parts)
            issues, correction = _validate_response(text, actions) if not fast_only else ([], None)
            if issues and not retried:
                retried = True
                logger.warning("Claude validation failed (%d issues), re-generating", len(issues))
                chat_msgs.append({"role": "assistant", "content": [{"type": "text", "text": text}]})
                chat_msgs.append({"role": "user", "content": [{"type": "text", "text":
                    "⚠ СТОП. Твой ответ содержит ошибки:\n" +
                    "\n".join(f"- {i}" for i in issues) +
                    "\n\nПерепиши ответ, исправив эти ошибки. Используй ТОЛЬКО данные из инструментов."
                }]})
                continue
            if correction and not issues:
                text += correction
            return {"message": text, "actions": actions, "pending_action": None}

        return {"message": "Достигнут лимит вызовов инструментов.", "actions": actions, "pending_action": None}

    # ------------------------------------------------------------------
    # Gemini
    # ------------------------------------------------------------------
    async def _chat_gemini(self, messages: list[dict], fast_only: bool = False, progress_queue: Optional[asyncio.Queue] = None) -> dict:
        tools = _tools_for_gemini(fast_only=fast_only)
        actions = []
        already_called = set()
        retried = False  # local flag to avoid cross-request leakage
        site_id = self._extract_site_id(messages)

        gemini_contents = []
        system_text = ""
        for m in messages:
            if m["role"] == "system":
                system_text += m["content"] + "\n"
            elif m["role"] == "user":
                gemini_contents.append({"role": "user", "parts": [{"text": m["content"]}]})
            elif m["role"] == "assistant":
                gemini_contents.append({"role": "model", "parts": [{"text": m.get("content", "")}]})

        if system_text and gemini_contents:
            first = gemini_contents[0]
            if first["role"] == "user":
                first["parts"][0]["text"] = system_text.strip() + "\n\n" + first["parts"][0]["text"]

        url = (
            f"https://generativelanguage.googleapis.com/v1beta/models/"
            f"{self.model}:generateContent?key={self.api_key}"
        )

        max_rounds = 5 if fast_only else 12
        max_tok = 2048 if fast_only else 8192

        for _ in range(max_rounds):
            # v3.2: Trim context (convert gemini_contents to estimate, trim if needed)
            _gc_tokens = sum(_estimate_tokens(json.dumps(c, ensure_ascii=False, default=str)) for c in gemini_contents)
            _gc_limit = int(_get_context_limit("gemini", self.model) * 0.80) - max_tok
            if _gc_tokens > _gc_limit and len(gemini_contents) > 4:
                logger.warning("Gemini context overflow: ~%d tokens, limit ~%d. Trimming.", _gc_tokens, _gc_limit)
                # Keep first 2 (system+user) and last 4 messages, drop middle
                gemini_contents = gemini_contents[:2] + gemini_contents[-4:]

            try:
                async with httpx.AsyncClient(timeout=self.timeout) as http:
                    body = {
                        "contents": gemini_contents,
                        "tools": [{"function_declarations": tools}],
                        "generationConfig": {"temperature": 0.3, "maxOutputTokens": max_tok},
                    }
                    resp = await http.post(url, json=body)
            except Exception as e:
                logger.error("Gemini error: %s", e)
                return {"message": _format_llm_error("gemini", e), "actions": actions, "pending_action": None}

            if resp.status_code != 200:
                try:
                    err = resp.json().get("error", {}).get("message", resp.text[:200])
                except Exception:
                    err = resp.text[:200]
                return {"message": _format_http_error("gemini", resp.status_code, err), "actions": actions, "pending_action": None}

            data = resp.json()
            candidate = data.get("candidates", [{}])[0]
            parts = candidate.get("content", {}).get("parts", [])
            text_parts = []
            function_calls = []
            for part in parts:
                if "text" in part:
                    text_parts.append(part["text"])
                if "functionCall" in part:
                    function_calls.append(part["functionCall"])

            if function_calls:
                # Silent tools: execute without burning a round
                _SILENT = {"update_investigation"}
                _text_combined = "\n".join(text_parts).strip()
                all_silent = all(fc["name"] in _SILENT for fc in function_calls)
                if all_silent:
                    for fc in function_calls:
                        try:
                            await execute_tool(fc["name"], fc.get("args", {}))
                        except Exception:
                            pass
                    if _text_combined:
                        return {"message": _text_combined, "actions": actions, "pending_action": None}
                    # No text yet — add tool results and continue WITHOUT burning a round
                    gemini_contents.append({"role": "model", "parts": parts})
                    gemini_contents.append({"role": "user", "parts": [
                        {"functionResponse": {"name": fc["name"], "response": {"result": "OK"}}} for fc in function_calls
                    ]})
                    continue

                gemini_contents.append({"role": "model", "parts": parts})
                func_responses = []
                auto_parts = []
                _auto_fu_count = 0  # v3.4 PERF: cap auto follow-ups

                for fc in function_calls:
                    tool_name = fc["name"]
                    tool_args = fc.get("args", {})
                    logger.info("Gemini tool call: %s(%s)", tool_name, tool_args)

                    if tool_name in DANGEROUS_TOOLS:
                        pending = self._build_pending_action(tool_name, tool_args)
                        text = "\n".join(text_parts) if text_parts else ""
                        return {"message": (text + "\n\n" + pending["description"]).strip(), "actions": actions, "pending_action": pending}

                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "running"})
                    result = await execute_tool(tool_name, tool_args)
                    if progress_queue:
                        await progress_queue.put({"type": "step", "tool": tool_name, "status": "done"})
                    already_called.add(tool_name)
                    summary = _summarize_tool_result(tool_name, result)
                    actions.append({"tool": tool_name, "args": tool_args, "result": result})
                    func_responses.append({"functionResponse": {"name": tool_name, "response": {"summary": summary}}})

                    # v4.1 PERF: execute L1 follow-ups in PARALLEL
                    if _auto_fu_count < 3:
                        followups = await _detect_anomalies(tool_name, result, already_called, site_id or tool_args.get("site_id")) if not fast_only else []
                    else:
                        followups = []
                    followups = followups[:max(0, 3 - _auto_fu_count)]
                    if followups:
                        if progress_queue:
                            for fu in followups:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "running", "auto": True})
                        fu_results = await asyncio.gather(
                            *[execute_tool(fu["name"], fu["args"]) for fu in followups],
                            return_exceptions=True,
                        )
                        for fu, fu_result in zip(followups, fu_results):
                            if isinstance(fu_result, Exception):
                                logger.warning("Auto follow-up %s failed: %s", fu["name"], fu_result)
                                continue
                            if progress_queue:
                                await progress_queue.put({"type": "step", "tool": fu["name"], "status": "done", "auto": True})
                            already_called.add(fu["name"])
                            fu_summary = _summarize_tool_result(fu["name"], fu_result)
                            actions.append({"tool": fu["name"], "args": fu["args"], "result": fu_result})
                            logger.info("Auto follow-up: %s — %s", fu["name"], fu["reason"])
                            auto_parts.append({"text": f"[Авто: {fu['name']}] {fu['reason']}\n{fu_summary}"})
                            _auto_fu_count += 1

                gemini_contents.append({"role": "user", "parts": func_responses})
                if auto_parts:
                    gemini_contents.append({"role": "user", "parts": auto_parts})
                continue

            text = "\n".join(text_parts)
            issues, correction = _validate_response(text, actions) if not fast_only else ([], None)
            if issues and not retried:
                retried = True
                logger.warning("Gemini validation failed (%d issues), re-generating", len(issues))
                gemini_contents.append({"role": "model", "parts": [{"text": text}]})
                gemini_contents.append({"role": "user", "parts": [{"text":
                    "⚠ СТОП. Твой ответ содержит ошибки:\n" +
                    "\n".join(f"- {i}" for i in issues) +
                    "\n\nПерепиши ответ, исправив эти ошибки. Используй ТОЛЬКО данные из инструментов."
                }]})
                continue
            if correction and not issues:
                text += correction
            return {"message": text, "actions": actions, "pending_action": None}

        return {"message": "Достигнут лимит вызовов инструментов.", "actions": actions, "pending_action": None}

