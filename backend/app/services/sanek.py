# ---------------------------------------------------------------------------
def _detect_time_patterns(incidents: list[dict]) -> list[str]:
    """Analyze incidents and find temporal patterns.

    incidents: list of dicts with keys: started_at (datetime), alarm_code (str), device_id (int)
    Returns list of human-readable observations in Russian.
    """
    observations = []
    if len(incidents) < 2:
        return observations

    from collections import Counter

    # 1. Recurring time-of-day
    hours = [inc["started_at"].hour for inc in incidents if inc.get("started_at")]
    hour_counts = Counter(hours)
    for hour, count in hour_counts.items():
        if count >= 3:
            observations.append(
                f"⚠️ Паттерн: {count} остановок в промежутке "
                f"{hour:02d}:00–{(hour + 1) % 24:02d}:00 за анализируемый период. "
                f"Возможно плановое отключение по расписанию."
            )

    # 2. Recurring day-of-week
    DAYS_RU = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
    weekdays = [inc["started_at"].weekday() for inc in incidents if inc.get("started_at")]
    day_counts = Counter(weekdays)
    for day, count in day_counts.items():
        if count >= 2 and len(incidents) >= 4:
            observations.append(
                f"⚠️ Паттерн: {count} остановок в {DAYS_RU[day]}. "
                f"Возможно еженедельное техобслуживание."
            )

    # 3. Increasing frequency (degradation trend)
    if len(incidents) >= 4:
        mid = len(incidents) // 2
        first_half = mid
        second_half = len(incidents) - mid
        if second_half > first_half * 1.5:
            observations.append(
                f"📈 Тренд: частота остановок растёт — "
                f"{first_half} в первой половине vs {second_half} во второй. "
                f"Возможна деградация оборудования."
            )

    # 4. Same alarm code repeating
    codes = [inc["alarm_code"] for inc in incidents if inc.get("alarm_code")]
    code_counts = Counter(codes)
    for code, count in code_counts.items():
        if count >= 3:
            human_code = HUMAN_READABLE.get(code, code)
            observations.append(
                f"🔁 Повтор: '{human_code}' — {count} раз за период. "
                f"Системная проблема, не случайный сбой."
            )

    return observations


