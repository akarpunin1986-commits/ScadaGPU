# Max input tokens per provider/model (conservative estimates)
_CONTEXT_LIMITS = {
    "gpt-4o": 128_000,
    "gpt-5": 128_000,
    "claude": 200_000,
    "gemini": 1_000_000,
    "grok": 128_000,
}


def _estimate_tokens(text: str) -> int:
    """Rough token estimate for mixed Russian/English/JSON text.

    BPE tokenizers: ~1 token per 4 chars for English, ~1 per 1.5-2 chars
    for Cyrillic. Use conservative 1:2.5 ratio for mixed content.
    """
    if not text:
        return 0
    return max(1, len(text) // 2)


def _estimate_messages_tokens(messages: list[dict]) -> int:
    """Estimate total tokens across all messages (including role overhead)."""
    total = 0
    for m in messages:
        total += 4  # role/separator overhead
        content = m.get("content", "")
        if isinstance(content, str):
            total += _estimate_tokens(content)
        elif isinstance(content, list):
            # Claude format: list of content blocks
            for block in content:
                if isinstance(block, dict):
                    total += _estimate_tokens(block.get("text", ""))
                    total += _estimate_tokens(json.dumps(block.get("input", ""), ensure_ascii=False, default=str) if "input" in block else "")
    return total


def _get_context_limit(provider: str, model: str) -> int:
    """Get context window limit for provider/model."""
    if "gpt-5" in model:
        return _CONTEXT_LIMITS["gpt-5"]
    if "gpt-4o" in model:
        return _CONTEXT_LIMITS["gpt-4o"]
    for key in ("claude", "gemini", "grok"):
        if key in provider or key in model:
            return _CONTEXT_LIMITS[key]
    return 128_000  # safe default


def _trim_context(messages: list[dict], provider: str, model: str,
                   max_output_tokens: int = 8192) -> list[dict]:
    """Trim message history to fit within context window.

    Strategy:
    - Never trim: system messages (first 1-3), last 2 user/assistant pairs
    - Trim first: tool results in the middle (shorten to 2000 chars)
    - Trim second: oldest conversation turns (drop entirely)
    """
    limit = _get_context_limit(provider, model)
    safe_limit = int(limit * 0.80) - max_output_tokens  # 80% minus output reserve

    current = _estimate_messages_tokens(messages)
    if current <= safe_limit:
        return messages

    logger.warning("Context overflow: ~%d tokens, limit ~%d. Trimming.", current, safe_limit)

    # Phase 1: Find system messages (protected) and conversation messages
    system_count = 0
    for m in messages:
        if m.get("role") == "system":
            system_count += 1
        else:
            break

    # Protect: system messages + last 4 conversation messages (2 user/assistant pairs)
    protected_tail = 4
    trimmable = messages[system_count:-protected_tail] if len(messages) > system_count + protected_tail else []
    head = messages[:system_count]
    tail = messages[-protected_tail:] if len(messages) > system_count + protected_tail else messages[system_count:]

    # Phase 2: Shorten tool results in trimmable section
    trimmed_middle = []
    for m in trimmable:
        content = m.get("content", "")
        if isinstance(content, str) and m.get("role") in ("tool", "user") and len(content) > 3000:
            # Aggressively shorten tool/auto-followup content
            trimmed_middle.append({**m, "content": content[:1500] + f"\n... [обрезано: {len(content)} → 1500 символов]"})
        else:
            trimmed_middle.append(m)

    result = head + trimmed_middle + tail
    current = _estimate_messages_tokens(result)
    if current <= safe_limit:
        logger.info("Context trimmed (phase 2): ~%d tokens", current)
        return result

    # Phase 3: Drop oldest conversation turns until it fits
    while trimmed_middle and current > safe_limit:
        dropped = trimmed_middle.pop(0)
        logger.debug("Dropping message role=%s len=%d", dropped.get("role"), len(str(dropped.get("content", ""))))
        result = head + trimmed_middle + tail
        current = _estimate_messages_tokens(result)

    logger.info("Context trimmed (phase 3): ~%d tokens, %d messages remain", current, len(result))
    return result


