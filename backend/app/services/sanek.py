_investigation_redis = None  # lazy singleton


async def _get_inv_redis():
    """Lazy Redis client for investigation storage."""
    global _investigation_redis
    if _investigation_redis is None:
        from redis.asyncio import Redis as AioRedis
        _investigation_redis = AioRedis.from_url(settings.REDIS_URL, decode_responses=True)
    return _investigation_redis


async def _get_investigation(conv_id: str) -> dict | None:
    """Load active investigation from Redis."""
    if not conv_id:
        return None
    try:
        r = await _get_inv_redis()
        raw = await r.get(f"sanek:investigation:{conv_id}")
        return json.loads(raw) if raw else None
    except Exception as e:
        logger.warning("Investigation load error: %s", e)
        return None


async def _update_investigation(conv_id: str, update: dict):
    """Merge new facts/questions into investigation context."""
    if not conv_id:
        return
    try:
        current = await _get_investigation(conv_id) or {}

        # Merge key_facts (deduplicate, max 10)
        if "key_facts" in update:
            facts = current.get("key_facts", [])
            for fact in update["key_facts"]:
                if fact not in facts:
                    facts.append(fact)
            current["key_facts"] = facts[-10:]

        # Merge open_questions (deduplicate, max 5)
        if "open_questions" in update:
            questions = current.get("open_questions", [])
            for q in update["open_questions"]:
                if q not in questions:
                    questions.append(q)
            current["open_questions"] = questions[-5:]

        # Overwrite scalar fields
        current.update({k: v for k, v in update.items()
                        if k not in ("key_facts", "open_questions")})
        current["last_updated"] = datetime.now(timezone.utc).isoformat()

        r = await _get_inv_redis()
        await r.setex(
            f"sanek:investigation:{conv_id}",
            7200,  # TTL 2 hours
            json.dumps(current, ensure_ascii=False),
        )
    except Exception as e:
        logger.warning("Investigation update error: %s", e)


async def _close_investigation(conv_id: str):
    """Delete investigation (topic changed)."""
    if not conv_id:
        return
    try:
        r = await _get_inv_redis()
        await r.delete(f"sanek:investigation:{conv_id}")
    except Exception:
        pass


