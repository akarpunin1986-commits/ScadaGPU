    def _build_pending_action(self, tool_name: str, tool_args: dict) -> dict:
        """Build a pending action that requires operator confirmation."""
        if tool_name == "send_command":
            cmd = tool_args.get("command", "")
            dev_id = tool_args.get("device_id", "?")
            label = COMMAND_LABELS.get(cmd, cmd)
            desc = f"⚠ {label} устройства ID={dev_id}?\n\nОтветьте «Да» для подтверждения или «Нет» для отмены."
        elif tool_name == "set_power_limit":
            dev_id = tool_args.get("device_id", "?")
            p = tool_args.get("p_percent") or tool_args.get("power_percent", "—")
            # Fallback: если LLM передал строку вместо числа
            if isinstance(p, str) and "%" in p:
                try:
                    p = float(p.replace("%", "").strip())
                    tool_args["p_percent"] = p
                except ValueError:
                    pass
            q = tool_args.get("q_percent", "—")
            desc = f"⚠ Установить лимит мощности устройства ID={dev_id}: P={p}%?\n\nОтветьте «Да» для подтверждения или «Нет» для отмены."
        else:
            desc = f"⚠ Выполнить {tool_name}?"

        return {
            "tool": tool_name,
            "args": tool_args,
            "description": desc,
        }

    @staticmethod
    def _extract_site_id(messages: list[dict]) -> int | None:
        """Extract site_id from operator context or user messages."""
        # 1. Check system context hint: [Контекст оператора] ... site_id=N
        for m in messages:
            if m.get("role") == "system":
                content = m.get("content", "")
                match = re.search(r"site_id=(\d+)", content)
                if match:
                    return int(match.group(1))
        # 2. Check user messages for site mentions (dynamic from cache)
        cached_site_map = _prompt_cache.get("site_map", {})
        cached_dev_to_site = _prompt_cache.get("dev_to_site", {})
        for m in reversed(messages):
            if m.get("role") == "user":
                text = m.get("content", "").lower()
                for key, sid in cached_site_map.items():
                    if key in text:
                        return sid
                # Check for device mentions → derive site_id
                gen_match = re.search(r"генератор[аеу]?\s*(\d)", text)
                if gen_match:
                    dev_id = gen_match.group(1)
                    sid = cached_dev_to_site.get(dev_id)
                    if sid:
                        return sid
        return None
