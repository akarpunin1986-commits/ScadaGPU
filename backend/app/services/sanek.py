def _summarize_query_data(data) -> str:
    """Smart formatter for query_data results — produces presentation-ready output for LLM.

    Key principle: format data so LLM can show it directly to the operator
    without needing to re-interpret or aggregate.
    Handles both list (legacy) and dict (DataResponse v5.0) formats.
    """
    # v5.0: DataResponse dict format
    if isinstance(data, dict):
        if "error" in data:
            return f"Ошибка: {data['error']}"
        entity = data.get("entity", "?")
        rows = data.get("data", [])
        cnt = data.get("count", len(rows))
        period = data.get("period", "")
        group_by = data.get("group_by", "")
        agg = data.get("aggregation", "")
        flt = data.get("filters", {})

        if not rows:
            return f"📊 {entity}: данных нет за период {period or 'не указан'}. Фильтры: {flt}"

        # Header
        header = f"📊 {entity} ({cnt} записей"
        if period:
            header += f", период: {period}"
        if group_by:
            header += f", группировка: {group_by}"
        if agg:
            header += f", агрегация: {agg}"
        header += f", фильтры: {flt})" if flt else ")"

        # For entity-based results, delegate to row formatter
        data = rows  # fall through to list handling below
        # Prepend entity header
        _entity_header = header
    else:
        _entity_header = None

    if not data:
        return "Данных нет за указанный период."
    n = len(data)

    # --- Single aggregation result ---
    if n == 1 and "aggregation" in data[0]:
        lines = [f"📊 Агрегация ({data[0]['aggregation']}, {data[0].get('count', 0)} точек):"]
        for k, v in data[0].items():
            if k not in ("aggregation", "count"):
                if isinstance(v, float):
                    lines.append(f"  {k}: {v:.1f}")
                else:
                    lines.append(f"  {k}: {v}")
        return _humanize("\n".join(lines))

    # --- Detect time granularity ---
    granularity = "точки"
    if n >= 2:
        try:
            ts0 = data[0].get("timestamp") or data[0].get("bucket") or ""
            ts1 = data[1].get("timestamp") or data[1].get("bucket") or ""
            from datetime import datetime as _dt
            t0 = _dt.fromisoformat(str(ts0).replace("Z", "").replace("+00:00", ""))
            t1 = _dt.fromisoformat(str(ts1).replace("Z", "").replace("+00:00", ""))
            delta_min = abs((t1 - t0).total_seconds()) / 60
            if delta_min >= 1380:  # ~23h = daily
                granularity = "по дням"
            elif delta_min >= 55:  # ~1h = hourly
                granularity = "по часам"
            elif delta_min >= 25:  # ~30min
                granularity = "по 30 мин"
            elif delta_min >= 4:  # ~5min
                granularity = "по 5 мин"
            else:
                granularity = "поминутно"
        except Exception:
            pass

    # --- Get metric keys (excluding meta) ---
    meta_keys = {"timestamp", "bucket", "online", "sample_count", "aggregation", "count"}
    first = data[0]
    metric_keys = [k for k in first if k not in meta_keys and first.get(k) is not None]

    # --- Format timestamp for display ---
    def _fmt_ts(row: dict) -> str:
        ts = row.get("timestamp") or row.get("bucket") or "?"
        ts_str = str(ts).replace("T", " ").replace("Z", "").replace("+00:00", "")
        if granularity == "по дням" and len(ts_str) > 10:
            return ts_str[:10]  # just the date
        if granularity == "по часам" and len(ts_str) > 16:
            return ts_str[:16]  # date + HH:MM
        return ts_str[:19]

    # --- Build formatted output ---
    lines = [_entity_header or f"📊 Данные {granularity} ({n} записей):"]

    first_row = data[0]
    last_row = data[-1]
    lines.append(f"Период: {_fmt_ts(first_row)} — {_fmt_ts(last_row)}")
    lines.append(f"Метрики: {', '.join(metric_keys)}")
    lines.append("")

    # For small datasets (≤50 points) — show EVERY row as a table
    if n <= 50:
        lines.append("ТАБЛИЦА (покажи КАЖДУЮ строку оператору):")
        for row in data:
            ts = _fmt_ts(row)
            parts = []
            for k in metric_keys:
                v = row.get(k)
                if v is not None:
                    if isinstance(v, float):
                        parts.append(f"{k}={v:.1f}")
                    else:
                        parts.append(f"{k}={v}")
            lines.append(f"  {ts} | {', '.join(parts)}")

        # Add per-metric summary
        lines.append("")
        lines.append("ИТОГО:")
        for k in metric_keys:
            values = [r.get(k) for r in data if r.get(k) is not None and isinstance(r.get(k), (int, float))]
            if values:
                lines.append(f"  {k}: min={min(values):.1f}, avg={sum(values)/len(values):.1f}, max={max(values):.1f}")

    else:
        # Large dataset: summary + first/last 5 points
        lines.append("СВОДКА (большой объём данных):")
        for k in metric_keys:
            values = [r.get(k) for r in data if r.get(k) is not None and isinstance(r.get(k), (int, float))]
            if values:
                lines.append(f"  {k}: min={min(values):.1f}, avg={sum(values)/len(values):.1f}, max={max(values):.1f}")

        lines.append(f"\nПервые 5 точек:")
        for row in data[:5]:
            ts = _fmt_ts(row)
            parts = [f"{k}={row.get(k):.1f}" if isinstance(row.get(k), float) else f"{k}={row.get(k)}" for k in metric_keys if row.get(k) is not None]
            lines.append(f"  {ts} | {', '.join(parts)}")
        lines.append(f"Последние 5 точек:")
        for row in data[-5:]:
            ts = _fmt_ts(row)
            parts = [f"{k}={row.get(k):.1f}" if isinstance(row.get(k), float) else f"{k}={row.get(k)}" for k in metric_keys if row.get(k) is not None]
            lines.append(f"  {ts} | {', '.join(parts)}")

    # --- Add presentation hint ---
    lines.append("")
    lines.append(f"ИНСТРУКЦИЯ: Оператор запросил данные {granularity}. Покажи КАЖДУЮ строку таблицы — НЕ агрегируй в одну цифру.")

    return _humanize("\n".join(lines))


