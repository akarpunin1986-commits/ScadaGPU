def _validate_response(response_text: str, tool_data: list[dict]) -> tuple[list[str], str | None]:
    """
    Validate LLM response against tool data.
    Returns (issues_list, correction_text_or_none).
    issues_list is used to decide whether to re-generate.
    """
    if not response_text or not tool_data:
        return [], None
    resp_lower = response_text.lower()
    issues = []
    facts = []  # factual data to inject into re-generation prompt
    try:
        for td in tool_data:
            tn = td.get("tool", "")
            res = td.get("result")
            if not res:
                continue

            if tn == "get_system_summary" and isinstance(res, dict):
                has_stopped = False
                stopped_names = []
                for site in res.get("sites", []):
                    for dev in site.get("devices", []):
                        if dev.get("type") != "ats" and not dev.get("is_running"):
                            has_stopped = True
                            stopped_names.append(f"{dev.get('name','')} (gen_status={dev.get('gen_status')})")
                if has_stopped:
                    bad_phrases = ["всё в порядке", "все в порядке", "штатн", "ошибок нет", "проблем нет",
                                   "нормальн", "без замечаний", "работает стабильно", "работают штатно"]
                    if any(bp in resp_lower for bp in bad_phrases):
                        issues.append(f"Ответ говорит 'всё в порядке', но НЕ РАБОТАЮТ: {', '.join(stopped_names)}")
                        facts.append(f"ФАКТ: {', '.join(stopped_names)} — НЕ РАБОТАЮТ")
                    # Also check if stopped generators not mentioned at all
                    for sn in stopped_names:
                        dev_name = sn.split(" (")[0].lower()
                        if dev_name not in resp_lower and "не работа" not in resp_lower:
                            issues.append(f"Ответ не упоминает остановленный {sn}")
                            facts.append(f"ФАКТ: {sn} НЕ РАБОТАЕТ — нужно явно сообщить оператору")

            elif tn == "analyze_incident" and isinstance(res, dict):
                s = res.get("summary", {})
                actual_h = s.get("total_downtime_hours", 0)
                if actual_h > 0.5:
                    zero_phrases = ["простой: 0", "простоя нет", "0 часов простоя", "простоев: 0",
                                    "простоев нет", "без простоев", "простоев не было"]
                    if any(zp in resp_lower for zp in zero_phrases):
                        issues.append(f"Ответ говорит '0 простоя', данные: {actual_h}ч простоя")
                        facts.append(f"ФАКТ: Реальный простой = {actual_h} часов ({s.get('total_downtime_minutes',0)} мин)")

                actual_lost = s.get("estimated_energy_lost_kwh", 0)
                if actual_lost > 100:
                    if "потерь нет" in resp_lower or "без потерь" in resp_lower or "0 квт" in resp_lower:
                        issues.append(f"Ответ говорит 'потерь нет', данные: ~{actual_lost} кВт·ч потеряно")
                        facts.append(f"ФАКТ: Потери энергии ≈ {actual_lost} кВт·ч")

                # V3.2: Catch nominal-based loss (nominal × hours instead of avg × hours)
                nominal_per_gen = s.get("nominal_power_per_gen_kw", 0)
                if actual_lost > 0 and actual_h > 0 and nominal_per_gen > 0:
                    nominal_lost = round(nominal_per_gen * actual_h, 1)
                    # If LLM mentions nominal-based number and it differs from actual by >15%
                    if nominal_lost != actual_lost and abs(nominal_lost - actual_lost) / max(actual_lost, 1) > 0.15:
                        nominal_str = str(int(nominal_lost))
                        if nominal_str in response_text:
                            issues.append(
                                f"Ответ содержит {nominal_str} кВт·ч (= {nominal_per_gen} кВт × {actual_h} ч, номинал!). "
                                f"Правильно: {actual_lost} кВт·ч (средняя мощность × простой)"
                            )
                            facts.append(
                                f"ФАКТ: Потери = {actual_lost} кВт·ч (по средней мощности {s.get('avg_running_power_kw', '?')} кВт). "
                                f"Число {nominal_str} — ОШИБКА (использует номинал вместо среднего)."
                            )

                # V3.3: Check false "output reduction" when running generators are at full power
                dev_list = res.get("devices_analysis", [])
                gen_devs = [d for d in dev_list if d.get("type") == "генератор"]
                running_gens = [d for d in gen_devs if (d.get("utilization_pct") or 0) > 70]
                stopped_gens = [d for d in gen_devs if (d.get("utilization_pct") or 0) <= 10]
                if running_gens and stopped_gens:
                    false_decline_phrases = ["снижение выработки", "падение выработки", "снижении выработки",
                                             "падении выработки", "выработка снизилась", "выработка упала"]
                    if any(fp in resp_lower for fp in false_decline_phrases):
                        running_names = ", ".join(d.get("name", "") for d in running_gens)
                        stopped_names_v = ", ".join(d.get("name", "") for d in stopped_gens)
                        issues.append(
                            f"Ответ говорит 'снижение/падение выработки', но {running_names} работает на полной мощности! "
                            f"Правильно: 'потери от простоя {stopped_names_v}', а НЕ 'снижение выработки'."
                        )
                        facts.append(
                            f"ФАКТ: {running_names} работает на >70% номинала (загрузка OK). "
                            f"Потери вызваны простоем {stopped_names_v}, а НЕ снижением мощности работающих."
                        )

                # V3.1: Check fabricated stop reasons
                # If downtime exists but no alarms explain it, and response claims specific reason
                alarm_count = s.get("total_alarms", 0)
                shutdown_count = s.get("shutdown_alarms", 0)
                if actual_h > 1 and shutdown_count == 0 and alarm_count == 0:
                    fabricated_reasons = ["плановое то", "техобслуживание", "профилактик",
                                          "регламент", "плановый ремонт", "плановая остановка",
                                          "сервисное обслуживание"]
                    for fr in fabricated_reasons:
                        if fr in resp_lower:
                            issues.append(f"Ответ утверждает '{fr}', но в данных нет аварий/событий, подтверждающих причину остановки")
                            facts.append(f"ФАКТ: Простой {actual_h}ч, но аварий: 0, shutdown-событий: 0. Причина НЕ ОПРЕДЕЛЕНА по данным СКАДА.")

            elif tn == "get_alarms" and isinstance(res, (list, dict)):
                alarms = res if isinstance(res, list) else res.get("alarms", [])
                if len(alarms) > 0:
                    if "аварий нет" in resp_lower or "ошибок нет" in resp_lower:
                        issues.append(f"Ответ говорит 'аварий нет', данные: {len(alarms)} аварий")
                        facts.append(f"ФАКТ: {len(alarms)} активных аварий")

        if issues:
            correction = "\n\n⚠️ **Автопроверка обнаружила расхождения:**\n" + "\n".join(f"- {i}" for i in issues)
            return issues, correction
    except Exception as e:
        logger.warning("Response validation error: %s", e)
    return [], None


