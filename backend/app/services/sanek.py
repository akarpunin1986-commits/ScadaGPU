def _humanize(text: str) -> str:
    """Replace technical codes with human-readable Russian text."""
    if not text:
        return text
    for code, human in HUMAN_READABLE.items():
        if code in text:
            if human:
                text = text.replace(code, f"{human} ({code})")
            else:
                text = text.replace(code, "")
    text = re.sub(r'\s{2,}', ' ', text)
    return text.strip()


def _add_cost(lost_kwh: float, cost_per_kwh: float | None = None) -> str:
    """Format energy loss with ruble equivalent."""
    if cost_per_kwh is None:
        cost_per_kwh = 5.0  # default average ~5 ₽/kWh
    rub = lost_kwh * cost_per_kwh
    if rub >= 1000:
        return f"{lost_kwh:.0f} кВт·ч (~{rub / 1000:.1f} тыс. ₽)"
    return f"{lost_kwh:.0f} кВт·ч (~{rub:.0f} ₽)"


