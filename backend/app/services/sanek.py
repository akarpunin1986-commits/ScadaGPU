# v3.2: Auto-learning — correction detector
# ---------------------------------------------------------------------------
_CORRECTION_PATTERNS = re.compile(
    r"(?i)("
    r"неправильно|не\s*так|неверно|ошибка|ошибаешься|ошибся|"
    r"нет[\s,]+надо|нет[\s,]+нужно|нет[\s,]+правильно|нет[\s,]+должно|"
    r"не\s+\w+[\s,]+а\s+\w+|"  # "не X, а Y"
    r"всегда\s+делай|никогда\s+не|в\s+будущем|впредь|"
    r"я\s+(?:же\s+)?(?:говорил|просил|сказал)|"
    r"не\s+используй|используй\s+только|считай\s+(?:по|через)|"
    r"не\s+пиши|пиши\s+(?:только|всегда)|"
    r"не\s+показывай|показывай\s+(?:только|всегда)|"
    r"запомни|учти|имей\s+в\s+виду|обрати\s+внимание"
    r")"
)


def _detect_correction(messages: list[dict]) -> str | None:
    """
    Detect if the latest user message corrects Sanek's previous response.
    Returns a hint string for LLM injection, or None.
    """
    # Need at least: prev assistant + current user
    if len(messages) < 2:
        return None
    last_user = None
    prev_assistant = None
    for msg in reversed(messages):
        if msg["role"] == "user" and last_user is None:
            last_user = msg["content"]
        elif msg["role"] == "assistant" and last_user is not None:
            prev_assistant = msg["content"]
            break
    if not last_user or not prev_assistant:
        return None

    if _CORRECTION_PATTERNS.search(last_user):
        return (
            "[СИСТЕМА: Оператор КОРРЕКТИРУЕТ твой предыдущий ответ. "
            "Если это инструкция или предпочтение на будущее — ОБЯЗАТЕЛЬНО вызови remember "
            "с категорией instruction/preference, чтобы в следующий раз не повторять ошибку. "
            "Подтверди оператору, что запомнил.]"
        )
    return None


