# Dynamic prompt builder: loads sites/devices/nominals from DB
# ---------------------------------------------------------------------------
_prompt_cache: dict = {"sites_section": None, "nominals": {}, "site_map": {}, "dev_to_site": {}, "ts": 0}
_PROMPT_CACHE_TTL = 300  # refresh every 5 minutes


async def _build_sites_section() -> str:
    """Build dynamic sites/devices section from API (cached)."""
    import time
    now = time.time()
    if _prompt_cache["sites_section"] and (now - _prompt_cache["ts"]) < _PROMPT_CACHE_TTL:
        return _prompt_cache["sites_section"]
    try:
        async with httpx.AsyncClient(base_url=_API_BASE, timeout=5) as client:
            sites_resp = await client.get("/api/sites")
            sites_resp.raise_for_status()
            sites = sites_resp.json()
            devices_resp = await client.get("/api/devices")
            devices_resp.raise_for_status()
            devices = devices_resp.json()
            # Try to get registry for nominals
            try:
                reg_resp = await client.get("/api/registry/types")
                reg_resp.raise_for_status()
                registry = {r["type_code"]: r for r in reg_resp.json()}
            except Exception:
                registry = {}
        # Build nominals map: device_id → nominal_kw
        nominals = {}
        for d in devices:
            dtype = d.get("device_type", "generator")
            reg = registry.get(dtype, {})
            nom_vals = reg.get("nominal_values", {})
            nom_kw = nom_vals.get("power_kw") or nom_vals.get("power_total") or nom_vals.get("power")
            if not nom_kw:
                # Fallback: check thresholds
                thresholds = reg.get("thresholds", {})
                pt = thresholds.get("power_total", {})
                nom_kw = pt.get("nominal")
            nominals[d["id"]] = nom_kw  # None if unknown
        _prompt_cache["nominals"] = nominals
        # Group devices by site
        site_map = {}
        for s in sites:
            site_map[s["id"]] = {"name": s.get("name", f"Site#{s['id']}"), "devices": []}
        for d in devices:
            sid = d.get("site_id")
            if sid in site_map:
                nom = nominals.get(d["id"])
                nom_str = f", {int(nom)}кВт" if nom else ""
                site_map[sid]["devices"].append(
                    f"{d.get('name', '?')} (device_id={d['id']}{nom_str})"
                )
        lines = []
        for sid, info in site_map.items():
            devs = ", ".join(info["devices"])
            lines.append(f"{info['name']} (site_id={sid}): {devs}")
        section = "\n".join(lines)
        if not section:
            section = "(Нет объектов в системе)"
        _prompt_cache["sites_section"] = section
        # Build dynamic site name → site_id mapping for _extract_site_id
        name_map = {}
        dev_site_map = {}
        for s in sites:
            sname = s.get("name", "").lower()
            sid = s["id"]
            name_map[sname] = sid
            # Also add abbreviations (e.g., "МКЗ" from "МКЗ — Моргаушский ...")
            for part in sname.replace("—", " ").replace("-", " ").split():
                if len(part) >= 2:
                    name_map[part] = sid
        for d in devices:
            dev_site_map[str(d["id"])] = d.get("site_id")
        _prompt_cache["site_map"] = name_map
        _prompt_cache["dev_to_site"] = dev_site_map
        _prompt_cache["ts"] = now
        return section
    except Exception as e:
        logger.warning("Failed to build dynamic prompt, using fallback: %s", e)
        if _prompt_cache["sites_section"]:
            return _prompt_cache["sites_section"]
        return "(Ошибка загрузки объектов — используй get_sites и get_devices)"


async def _get_nominal_kw(device_id: int) -> float | None:
    """Get nominal power for a device from cache. Returns None if unknown."""
    import time
    if not _prompt_cache["nominals"] or (time.time() - _prompt_cache["ts"]) > _PROMPT_CACHE_TTL:
        await _build_sites_section()  # refresh cache
    return _prompt_cache["nominals"].get(device_id)


