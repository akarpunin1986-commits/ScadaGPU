def _analyze_trends(device_name: str, metrics_history: list[dict], nominals: dict) -> list[str]:
    """Analyze metric trends and warn about approaching thresholds.

    metrics_history: list of metric points (from device analysis)
    nominals: threshold values from device_type_registry
    Returns list of warning strings.
    """
    warnings = []
    if len(metrics_history) < 10:
        return warnings

    recent = metrics_history[-24:]  # ~2 hours at 5-min polling

    # 1. Coolant temperature trend
    temps = [p.get("coolant_temp") for p in recent if p.get("coolant_temp") is not None]
    if len(temps) >= 6:
        hours_span = len(temps) * 5 / 60
        if hours_span > 0:
            temp_delta_per_hour = (temps[-1] - temps[0]) / hours_span
            temp_threshold = nominals.get("coolant_temp_max", 95)
            if temp_delta_per_hour > 0.5 and temps[-1] < temp_threshold:
                hours_to_threshold = (temp_threshold - temps[-1]) / temp_delta_per_hour
                if 0 < hours_to_threshold < 8:
                    warnings.append(
                        f"🌡️ {device_name}: T ОЖ {temps[-1]:.1f}°C, "
                        f"растёт +{temp_delta_per_hour:.1f}°C/ч. "
                        f"До порога {temp_threshold}°C — "
                        f"{'менее часа' if hours_to_threshold < 1 else f'{hours_to_threshold:.1f} ч'}. "
                        f"Рекомендую проверить систему охлаждения."
                    )

    # 2. Oil pressure trend
    pressures = [p.get("oil_pressure") for p in recent if p.get("oil_pressure") is not None]
    if len(pressures) >= 6:
        hours_span = len(pressures) * 5 / 60
        if hours_span > 0:
            pressure_delta = (pressures[-1] - pressures[0]) / hours_span
            pressure_min = nominals.get("oil_pressure_min", 150)  # kPa
            if pressure_delta < -5 and pressures[-1] > pressure_min:  # dropping > 5 kPa/h
                hours_to_threshold = (pressures[-1] - pressure_min) / abs(pressure_delta)
                if 0 < hours_to_threshold < 8:
                    warnings.append(
                        f"🛢️ {device_name}: давление масла {pressures[-1]:.0f} кПа, "
                        f"падает {pressure_delta:.0f} кПа/ч. "
                        f"До порога {pressure_min} кПа — "
                        f"{'менее часа' if hours_to_threshold < 1 else f'{hours_to_threshold:.1f} ч'}."
                    )

    # 3. Frequency instability
    freqs = [p.get("frequency") or p.get("gen_freq") for p in recent
             if (p.get("frequency") or p.get("gen_freq")) is not None]
    if len(freqs) >= 6:
        freq_range = max(freqs) - min(freqs)
        if freq_range > 0.5:
            warnings.append(
                f"⚡ {device_name}: нестабильная частота — "
                f"разброс {min(freqs):.2f}–{max(freqs):.2f} Гц за последние 2 часа. "
                f"Норма: отклонение < 0.2 Гц. Возможна проблема с регулятором."
            )

    return warnings


