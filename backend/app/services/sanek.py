async def _get_data_start_hours(site_id: int | None) -> int:
    """
    Вычисляет кол-во часов от первой записи в БД до сейчас.
    Используется для all_time=True.
    Возвращает min 24, max 8760 (1 год).
    """
    try:
        devices = await _api_get("/api/devices", {"site_id": site_id} if site_id else {})
        if not isinstance(devices, list) or not devices:
            return 720  # fallback 30 дней

        earliest = None
        for dev in devices:
            did = dev.get("id")
            if not did:
                continue
            try:
                resp = await _api_get(
                    f"/api/history/metrics/{did}",
                    {"last_hours": 87600, "limit": 1, "fields": "power_total"},
                )
                records = resp.get("data", resp) if isinstance(resp, dict) else resp
                if isinstance(records, list) and records:
                    ts_str = records[0].get("timestamp") or records[0].get("time")
                    if ts_str:
                        ts = datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
                        if earliest is None or ts < earliest:
                            earliest = ts
            except Exception:
                continue

        if earliest is None:
            return 720

        now = datetime.now(tz=timezone.utc)
        hours = int((now - earliest).total_seconds() / 3600) + 1
        hours = max(hours, 24)
        hours = min(hours, 8760)  # cap 1 год
        logger.info("all_time for site_id=%s: earliest=%s, hours=%d", site_id, earliest.strftime("%d.%m.%Y"), hours)
        return hours
    except Exception as e:
        logger.warning("_get_data_start_hours failed: %s", e)
        return 720


async def _analyze_incident(
    site_id: int | None,
    device_id: int | None,
    last_hours: int,
) -> dict:
    """Analyze downtime/incident: alarms timeline, metric snapshots at alarm times, power drops, energy losses."""
    # v4.0 FIX: cap last_hours to prevent excessive data (API limits handled per-endpoint)
    if last_hours > 8760:
        last_hours = 8760  # max 1 year
    report = {
        "period_hours": last_hours,
        "alarms_timeline": [],
        "devices_analysis": [],
        "summary": {},
    }

    try:
        # Helper: convert UTC ISO string to MSK (UTC+3) display string
        def _utc_to_msk(iso_str: str | None) -> str | None:
            if not iso_str:
                return None
            try:
                dt = datetime.fromisoformat(str(iso_str).replace("Z", "").replace("+00:00", ""))
                msk = dt + timedelta(hours=3)
                return msk.strftime("%Y-%m-%d %H:%M:%S MSK")
            except Exception:
                return iso_str

        # 1. Get all alarm events for the period (from alarm_analytics — the working table)
        alarm_params: dict = {"last_hours": last_hours, "limit": _dynamic_limit(last_hours, base_per_hour=5, minimum=200, maximum=1000)}
        if device_id:
            alarm_params["device_id"] = device_id
        elif site_id:
            # Get site device IDs first for filtering
            pass
        alarms = await _api_get("/api/alarm-analytics/events", alarm_params)

        # Get device names + site names (for disambiguation)
        devices = await _api_get("/api/devices")
        sites_list = await _api_get("/api/sites")
        dev_map = {}
        site_name_map: dict[int, str] = {}  # site_id → short name (e.g. "МКЗ")
        if isinstance(sites_list, list):
            for s in sites_list:
                sname = s.get("name", f"Site#{s['id']}")
                # Extract short code (first word before "—" or full name)
                short = sname.split("—")[0].split("-")[0].strip() if "—" in sname or "-" in sname else sname
                site_name_map[s["id"]] = short.upper() if len(short) <= 5 else short
        if isinstance(devices, list):
            for d in devices:
                dev_map[d["id"]] = d

        # Filter by site if needed
        if site_id and not device_id:
            site_dev_ids = {d["id"] for d in devices if d.get("site_id") == site_id}
        else:
            site_dev_ids = None

        # 2. Build alarm timeline (chronological)
        if isinstance(alarms, list):
            for a in alarms:
                did = a.get("device_id")
                if site_dev_ids and did not in site_dev_ids:
                    continue
                dev_info = dev_map.get(did, {})
                # alarm_analytics fields differ from alarm_events
                occurred = a.get("occurred_at")
                cleared = a.get("cleared_at")
                _dev_site_id = dev_info.get("site_id")
                _dev_site_name = site_name_map.get(_dev_site_id, "") if _dev_site_id else ""
                entry = {
                    "time": _utc_to_msk(occurred),
                    "time_utc": occurred,
                    "cleared_at": _utc_to_msk(cleared),
                    "device_id": did,
                    "device_name": dev_info.get("name", f"#{did}"),
                    "site_id": _dev_site_id,
                    "site_name": _dev_site_name,
                    "device_type": dev_info.get("device_type", a.get("device_type", "?")),
                    "alarm_code": a.get("alarm_code"),
                    "severity": a.get("alarm_severity") or a.get("severity"),
                    "message": a.get("alarm_name_ru") or a.get("alarm_name") or a.get("message"),
                    "is_active": a.get("is_active", False),
                    "duration": _calc_alarm_duration(occurred) if a.get("is_active") else None,
                }
                if cleared and occurred:
                    try:
                        t0 = datetime.fromisoformat(str(occurred).replace("Z", "").replace("+00:00", ""))
                        t1 = datetime.fromisoformat(str(cleared).replace("Z", "").replace("+00:00", ""))
                        entry["duration_minutes"] = round((t1 - t0).total_seconds() / 60, 1)
                    except Exception:
                        pass
                report["alarms_timeline"].append(entry)

        # Sort by time_utc (raw UTC for ordering)
        report["alarms_timeline"].sort(key=lambda x: x.get("time_utc") or "")

        # 2.5. Get METRIC SNAPSHOTS at alarm times for root cause analysis
        # For each alarm event on a generator, fetch metrics around the alarm time
        _all_fields_gen = "power_total,coolant_temp,oil_pressure,engine_speed,fuel_level,gen_uab,gen_freq"
        alarm_metrics = []  # List of {alarm_time, device, metrics_before, metrics_at, metrics_after}
        processed_alarm_times = set()  # Avoid duplicate fetches for same device+time

        for alarm in report["alarms_timeline"]:
            acode = alarm.get("alarm_code", "")
            did = alarm.get("device_id")
            atime_utc = alarm.get("time_utc")  # Use UTC for API calls
            atime_msk = alarm.get("time")  # MSK for display
            dtype = alarm.get("device_type", "")
            if not did or not atime_utc or dtype != "generator":
                continue
            if acode == "CONN_LOST":
                continue
            # Deduplicate: same device within 2 minutes
            dedup_key = f"{did}_{str(atime_utc)[:16]}"
            if dedup_key in processed_alarm_times:
                continue
            processed_alarm_times.add(dedup_key)

            try:
                # Get metrics ±5 minutes around alarm time (UTC)
                alarm_dt = datetime.fromisoformat(str(atime_utc).replace("Z", "").replace("+00:00", ""))
                t_from = (alarm_dt - timedelta(minutes=5)).isoformat()
                t_to = (alarm_dt + timedelta(minutes=5)).isoformat()

                snap = await _api_get(f"/api/history/metrics/{did}", {
                    "fields": _all_fields_gen,
                    "start": t_from,
                    "end": t_to,
                    "limit": 200,
                })

                if isinstance(snap, list) and snap:
                    # Split into before/at/after alarm time
                    before = []
                    after = []
                    for pt in snap:
                        pts = pt.get("timestamp", "")
                        if pts < str(atime_utc):
                            before.append(pt)
                        else:
                            after.append(pt)

                    # Get key metric values: last before alarm, first after alarm
                    metrics_before = before[-1] if before else None
                    metrics_at = after[0] if after else (before[-1] if before else None)

                    # Build compact snapshot
                    snapshot = {
                        "alarm_time": atime_msk,
                        "alarm_code": acode,
                        "alarm_message": alarm.get("message", ""),
                        "device_id": did,
                        "device_name": alarm.get("device_name", ""),
                    }

                    if metrics_before:
                        snapshot["metrics_before_alarm"] = {
                            "timestamp": _utc_to_msk(metrics_before.get("timestamp")),
                            "power_kw": _rnd(metrics_before.get("power_total")),
                            "coolant_temp_C": _rnd(metrics_before.get("coolant_temp")),
                            "oil_pressure_kPa": _rnd(metrics_before.get("oil_pressure")),
                            "engine_speed_rpm": _rnd(metrics_before.get("engine_speed")),
                            "voltage_V": _rnd(metrics_before.get("gen_uab")),
                            "frequency_Hz": _rnd(metrics_before.get("gen_freq")),
                            "fuel_level_pct": _rnd(metrics_before.get("fuel_level")),
                        }

                    if metrics_at:
                        snapshot["metrics_at_alarm"] = {
                            "timestamp": _utc_to_msk(metrics_at.get("timestamp")),
                            "power_kw": _rnd(metrics_at.get("power_total")),
                            "coolant_temp_C": _rnd(metrics_at.get("coolant_temp")),
                            "oil_pressure_kPa": _rnd(metrics_at.get("oil_pressure")),
                            "engine_speed_rpm": _rnd(metrics_at.get("engine_speed")),
                            "voltage_V": _rnd(metrics_at.get("gen_uab")),
                            "frequency_Hz": _rnd(metrics_at.get("gen_freq")),
                            "fuel_level_pct": _rnd(metrics_at.get("fuel_level")),
                        }

                    # Trend: min/max of key params in the ±5 min window
                    all_powers = [pt.get("power_total") for pt in snap if pt.get("power_total") is not None]
                    all_temps = [pt.get("coolant_temp") for pt in snap if pt.get("coolant_temp") is not None]
                    all_oil = [pt.get("oil_pressure") for pt in snap if pt.get("oil_pressure") is not None]
                    all_speed = [pt.get("engine_speed") for pt in snap if pt.get("engine_speed") is not None]

                    snapshot["trend_5min"] = {}
                    if all_powers:
                        snapshot["trend_5min"]["power_kw"] = {"min": _rnd(min(all_powers)), "max": _rnd(max(all_powers))}
                    if all_temps:
                        snapshot["trend_5min"]["coolant_temp_C"] = {"min": _rnd(min(all_temps)), "max": _rnd(max(all_temps))}
                    if all_oil:
                        snapshot["trend_5min"]["oil_pressure_kPa"] = {"min": _rnd(min(all_oil)), "max": _rnd(max(all_oil))}
                    if all_speed:
                        snapshot["trend_5min"]["engine_speed_rpm"] = {"min": _rnd(min(all_speed)), "max": _rnd(max(all_speed))}

                    alarm_metrics.append(snapshot)

            except Exception as e:
                logger.warning("Failed to get metric snapshot for alarm at %s: %s", atime_utc, e)

        if alarm_metrics:
            report["alarm_metric_snapshots"] = alarm_metrics

        # 2.6. Auto-search knowledge base for each unique alarm type
        _ALARM_KB_QUERIES = {
            "SHUTDOWN": [
                "alarm shutdown trip over power over current",
                "coolant temperature oil pressure over speed",
                "reverse power under frequency over voltage",
            ],
            "COMMON": [
                "alarm warning common fault",
                "alarm shutdown trip protection",
            ],
            "WARNING": [
                "warning alarm maintenance service",
                "high temperature low pressure sensor",
            ],
            "BLOCK": [
                "alarm block interlock start failure",
                "alarm shutdown trip protection",
            ],
            "TRIP_STOP": [
                "emergency stop trip safety",
                "alarm shutdown trip protection",
            ],
        }

        kb_context = {}
        unique_alarm_codes = set()
        for a in report["alarms_timeline"]:
            code = a.get("alarm_code", "")
            if code and code != "CONN_LOST":
                unique_alarm_codes.add(code)

        for code in unique_alarm_codes:
            # Build search queries: exact code + parsed synonym + generic fallback
            synonym = _alarm_code_to_query(code)
            default_queries = [code]
            if synonym and synonym != code:
                default_queries.append(synonym)
            default_queries.append(f"{code} alarm protection")
            queries = _ALARM_KB_QUERIES.get(code, default_queries)
            all_results = []
            seen_ids = set()

            for q in queries:
                try:
                    results = await _api_get("/api/ai/knowledge/search", {"q": q, "limit": 5})
                    if isinstance(results, list):
                        for r in results:
                            rid = r.get("id")
                            if rid and rid not in seen_ids:
                                seen_ids.add(rid)
                                all_results.append({
                                    "title": r.get("title", ""),
                                    "content": r.get("content", "")[:1500],
                                    "source": r.get("source_filename", ""),
                                })
                except Exception as e:
                    logger.warning("KB search for alarm %s query '%s' failed: %s", code, q, e)

            if all_results:
                kb_context[code] = all_results[:5]

        if kb_context:
            report["knowledge_base_context"] = kb_context

        # 2.7. Fetch scada_events (journal) for state transitions context
        # These events explain WHY generators were idle: GEN_STATUS transitions, MODE_CHANGE, MAINS, etc.
        try:
            ev_params = {"last_hours": last_hours, "limit": _dynamic_limit(last_hours, base_per_hour=10, minimum=200, maximum=500)}
            if device_id:
                ev_params["device_id"] = device_id
            elif site_id:
                ev_params["site_id"] = site_id
            journal_events = await _api_get("/api/events", ev_params)
            if isinstance(journal_events, list) and journal_events:
                # Group journal events by device_id + convert timestamps to MSK
                _journal_by_device: dict[int, list] = {}
                for jev in journal_events:
                    did_j = jev.get("device_id")
                    if did_j is not None:
                        _journal_by_device.setdefault(did_j, []).append({
                            "time": _utc_to_msk(jev.get("created_at")),
                            "category": jev.get("category"),
                            "event_code": jev.get("event_code"),
                            "message": jev.get("message"),
                            "old_value": jev.get("old_value"),
                            "new_value": jev.get("new_value"),
                        })
                report["_journal_by_device"] = _journal_by_device
                report["journal_events_total"] = len(journal_events)

                # 2.8. Extract STATE TRANSITIONS (stops/starts) as first-class data
                # This is CRITICAL — these show actual generator stop/start times
                # even when no alarm was triggered (e.g. manual operator stops)
                state_transitions = []
                _critical_cats = {"GEN_CRITICAL", "GEN_STATUS", "MODE_CHANGE"}
                _stop_codes = {"gen_critical_stop", "gs_0", "gs_10", "gs_11", "gs_12", "gs_13", "gs_14", "gs_15"}
                _start_codes = {"gen_critical_start", "gs_1", "gs_2", "gs_3", "gs_4", "gs_5", "gs_6", "gs_7", "gs_8", "gs_9"}
                for jev in journal_events:
                    cat = jev.get("category", "")
                    code = jev.get("event_code", "")
                    if cat in _critical_cats and (code in _stop_codes or code in _start_codes or cat == "MODE_CHANGE"):
                        dev_info_j = dev_map.get(jev.get("device_id"), {})
                        _st_site_id = dev_info_j.get("site_id")
                        st_entry = {
                            "time": _utc_to_msk(jev.get("created_at")),
                            "device_id": jev.get("device_id"),
                            "device_name": dev_info_j.get("name", jev.get("device_name", f"#{jev.get('device_id')}")),
                            "site_id": _st_site_id,
                            "site_name": site_name_map.get(_st_site_id, "") if _st_site_id else "",
                            "type": "STOP" if code in _stop_codes else ("START" if code in _start_codes else "MODE"),
                            "message": jev.get("message", ""),
                            "event_code": code,
                        }
                        state_transitions.append(st_entry)

                if state_transitions:
                    # Sort chronologically (MSK strings sort correctly)
                    state_transitions.sort(key=lambda x: x.get("time") or "")
                    report["state_transitions"] = state_transitions
                    report["state_transitions_note"] = (
                        "ВАЖНО: state_transitions показывают ФАКТИЧЕСКИЕ остановки/запуски генераторов "
                        "по данным контроллера. Они включают ручные стопы оператором, которых НЕТ в alarms_timeline. "
                        "Используй state_transitions для определения ПЕРВОЙ остановки, а alarms_timeline — для причин аварий."
                    )
        except Exception as e:
            logger.warning("Failed to fetch journal events for incident analysis: %s", e)

        # 3. Analyze each device's metrics for the full period
        target_devices = []
        if device_id:
            if device_id in dev_map:
                target_devices = [dev_map[device_id]]
        elif site_dev_ids:
            target_devices = [dev_map[did] for did in site_dev_ids if did in dev_map]
        else:
            target_devices = list(dev_map.values())

        total_downtime_minutes = 0
        total_energy_lost_kwh = 0

        # v3.4 PERF: Parallel fetch — history + energy delta for ALL devices at once
        async def _fetch_dev_data(_dev):
            _did = _dev["id"]
            _dtype = _dev.get("device_type", "generator")
            _is_gen = _dtype == "generator"
            _fields = ("power_total,coolant_temp,oil_pressure,engine_speed,gen_uab,gen_freq,energy_kwh,run_hours"
                       if _is_gen else "mains_total_p,busbar_p,mains_uab,energy_kwh")
            if last_hours > 48:
                _bsec = max(300, int(last_hours * 3600 / 2000))
                _h_coro = _api_get(f"/api/history/metrics/{_did}/downsampled", {
                    "last_hours": last_hours, "fields": _fields, "bucket_seconds": _bsec,
                })
            else:
                _h_coro = _api_get(f"/api/history/metrics/{_did}", {
                    "last_hours": last_hours, "fields": _fields,
                    "limit": _dynamic_limit(last_hours, base_per_hour=120, minimum=1000, maximum=10000),
                })
            _ed_coro = _get_energy_delta(_did, last_hours, is_generator=_is_gen)
            _h, _ed = await asyncio.gather(_h_coro, _ed_coro)
            return (_did, _h, _ed)

        _fetch_results = await asyncio.gather(
            *[_fetch_dev_data(d) for d in target_devices], return_exceptions=True
        )
        _prefetched = {}
        for _fr in _fetch_results:
            if isinstance(_fr, tuple) and len(_fr) == 3:
                _prefetched[_fr[0]] = (_fr[1], _fr[2])
            elif isinstance(_fr, Exception):
                logger.warning("Parallel device fetch error: %s", _fr)

        for dev in target_devices:
            did = dev["id"]
            dtype = dev.get("device_type", "generator")
            dname = dev.get("name", f"#{did}")
            _dev_sid = dev.get("site_id")
            _dev_sname = site_name_map.get(_dev_sid, "") if _dev_sid else ""

            # Unpack pre-fetched data (history + energy delta)
            _pf = _prefetched.get(did)
            if not _pf:
                continue
            hist, ed = _pf

            if not isinstance(hist, list) or len(hist) < 2:
                # No data — treat as fully stopped, use nominal for losses
                dtype_display = "генератор" if dtype == "generator" else "ШПР" if dtype == "ats" else dtype
                _nom = await _get_nominal_kw(did) or 160.0
                _dt_min = round(last_hours * 60, 0)
                _lost = round(_nom * last_hours, 1) if dtype == "generator" else 0
                report["devices_analysis"].append({
                    "device_id": did,
                    "name": dname,
                    "site_id": _dev_sid,
                    "site_name": _dev_sname,
                    "type": dtype_display,
                    "nominal_power_kw": _nom,
                    "analysis_period_hours": last_hours,
                    "note": "Нет данных за период — устройство offline",
                    "data_points": 0,
                    "avg_power_kw": 0,
                    "avg_running_power_kw": 0,
                    "max_power_kw": 0,
                    "min_power_kw": 0,
                    "energy_kwh": 0,
                    "zero_power_periods": 1,
                    "downtime_minutes": _dt_min,
                    "estimated_lost_kwh": _lost,
                })
                continue

            # Analyze power data
            power_field = "power_total" if dtype == "generator" else "mains_total_p"
            powers = []
            zero_runs = []
            current_zero_start = None

            for pt in hist:
                p = pt.get(power_field)
                ts = pt.get("timestamp") or pt.get("bucket")
                if p is not None:
                    powers.append({"ts": ts, "p": float(p)})
                    if float(p) < 1.0:
                        if current_zero_start is None:
                            current_zero_start = ts
                    else:
                        if current_zero_start is not None:
                            zero_runs.append({"from": current_zero_start, "to": ts})
                            current_zero_start = None

            if current_zero_start is not None:
                zero_runs.append({"from": current_zero_start, "to": "now"})

            # Energy delta (already fetched in parallel above)
            energy_delta = ed["energy_delta"]
            rh_delta = ed["rh_delta"]
            energy_period_hours = ed.get("actual_hours") or last_hours  # real period of energy delta

            # Downtime calculation
            dev_downtime_min = 0
            for zr in zero_runs:
                try:
                    t0 = datetime.fromisoformat(str(zr["from"]).replace("Z", "").replace("+00:00", ""))
                    if zr["to"] == "now":
                        t1 = datetime.utcnow()
                    else:
                        t1 = datetime.fromisoformat(str(zr["to"]).replace("Z", "").replace("+00:00", ""))
                    dev_downtime_min += (t1 - t0).total_seconds() / 60
                except Exception:
                    pass
            # If device was down the ENTIRE window, find real outage start
            real_outage_start = None
            if dev_downtime_min >= (last_hours * 60 * 0.9) and len(zero_runs) == 1 and zero_runs[0].get("to") == "now":
                try:
                    # Query metrics further back to find last non-zero power
                    search_hours = min(last_hours * 30, 8760)  # up to 30x window, max 1 year
                    deep_hist = await _api_get(
                        f"/api/history/metrics/{did}/downsampled",
                        {"last_hours": search_hours, "fields": power_field, "bucket_seconds": 3600},
                    )
                    if deep_hist and isinstance(deep_hist, list):
                        # Walk backward to find last non-zero reading
                        for pt in reversed(deep_hist):
                            p_val = pt.get(power_field)
                            if p_val is not None and float(p_val) > 1.0:
                                ts_str = pt.get("timestamp") or pt.get("bucket")
                                real_outage_start = datetime.fromisoformat(
                                    str(ts_str).replace("Z", "").replace("+00:00", "")
                                )
                                real_downtime_min = (datetime.utcnow() - real_outage_start).total_seconds() / 60
                                dev_downtime_min = real_downtime_min
                                logger.info("Device %d: real outage start %s (%.0f min)", did, real_outage_start, real_downtime_min)
                                break
                except Exception as e:
                    logger.warning("Deep outage search failed for device %d: %s", did, e)

            total_downtime_minutes += dev_downtime_min

            # Estimate lost energy — use NOMINAL power (not neighbor avg)
            nominal_kw = await _get_nominal_kw(did) or 160.0
            avg_p = sum(x["p"] for x in powers) / len(powers) if powers else 0
            non_zero_p = [x["p"] for x in powers if x["p"] > 1.0]
            avg_running_p = sum(non_zero_p) / len(non_zero_p) if non_zero_p else 0
            estimated_lost_kwh = round(nominal_kw * (dev_downtime_min / 60), 1) if dev_downtime_min > 0 else 0
            total_energy_lost_kwh += estimated_lost_kwh

            # Calculate actual data span from timestamps (for accurate plan)
            data_span_h = last_hours  # default fallback
            running_hours_calc = None
            if hist and len(hist) >= 2:
                try:
                    _first_ts = hist[0].get("timestamp") or hist[0].get("bucket")
                    _last_ts = hist[-1].get("timestamp") or hist[-1].get("bucket")
                    _t0 = datetime.fromisoformat(str(_first_ts).replace("Z", "").replace("+00:00", ""))
                    _t1 = datetime.fromisoformat(str(_last_ts).replace("Z", "").replace("+00:00", ""))
                    data_span_h = round((_t1 - _t0).total_seconds() / 3600, 1)
                    if data_span_h < 0.1:
                        data_span_h = last_hours
                    # Calculate actual running hours from data (non-zero power)
                    running_hours_calc = round(data_span_h - (dev_downtime_min / 60), 1)
                    if running_hours_calc < 0:
                        running_hours_calc = 0
                except Exception:
                    pass

            dev_analysis = {
                "device_id": did,
                "name": dname,
                "site_id": _dev_sid,
                "site_name": _dev_sname,
                "type": "генератор" if dtype == "generator" else "ШПР",
                "analysis_period_hours": last_hours,
                "nominal_power_kw": nominal_kw,
                "data_points": len(hist),
                "avg_power_kw": round(avg_p, 1),
                "avg_running_power_kw": round(avg_running_p, 1),
                "max_power_kw": round(max(x["p"] for x in powers), 1) if powers else 0,
                "min_power_kw": round(min(x["p"] for x in powers), 1) if powers else 0,
                "energy_kwh": energy_delta,
                "zero_power_periods": len(zero_runs),
                "downtime_minutes": round(dev_downtime_min, 0),
                "estimated_lost_kwh": estimated_lost_kwh,
                "data_span_hours": data_span_h,
                "energy_period_hours": energy_period_hours,
                "running_hours": running_hours_calc,
            }
            if real_outage_start:
                dev_analysis["outage_start"] = _utc_to_msk(real_outage_start.isoformat())
                dev_analysis["total_outage_hours"] = round(dev_downtime_min / 60, 1)
                dev_analysis["downtime_note"] = (
                    f"Генератор стоит с {_utc_to_msk(real_outage_start.isoformat())} — "
                    f"полный простой {round(dev_downtime_min / 60, 1)} ч "
                    f"({round(dev_downtime_min / 60 / 24, 1)} дн.). "
                    f"Используй total_outage_hours для расчёта потерь, НЕ period_hours."
                )
            if rh_delta is not None:
                dev_analysis["run_hours_delta"] = rh_delta
            if zero_runs:
                dev_analysis["zero_power_details"] = [
                    {"from": _utc_to_msk(zr["from"]), "to": _utc_to_msk(zr["to"]) if zr["to"] != "now" else "сейчас"}
                    for zr in zero_runs[:10]
                ]

            # Full-period metric ranges for generators
            if dtype == "generator":
                temps = [pt.get("coolant_temp") for pt in hist if pt.get("coolant_temp") is not None]
                oils = [pt.get("oil_pressure") for pt in hist if pt.get("oil_pressure") is not None]
                speeds = [pt.get("engine_speed") for pt in hist if pt.get("engine_speed") is not None]
                freqs = [pt.get("gen_freq") for pt in hist if pt.get("gen_freq") is not None]
                volts = [pt.get("gen_uab") for pt in hist if pt.get("gen_uab") is not None]

                if temps:
                    dev_analysis["coolant_temp_C"] = {"min": _rnd(min(temps)), "max": _rnd(max(temps)), "avg": _rnd(sum(temps)/len(temps))}
                if oils:
                    dev_analysis["oil_pressure_kPa"] = {"min": _rnd(min(oils)), "max": _rnd(max(oils)), "avg": _rnd(sum(oils)/len(oils))}
                if speeds:
                    dev_analysis["engine_speed_rpm"] = {"min": _rnd(min(speeds)), "max": _rnd(max(speeds)), "avg": _rnd(sum(speeds)/len(speeds))}
                if freqs:
                    dev_analysis["frequency_Hz"] = {"min": _rnd(min(freqs)), "max": _rnd(max(freqs)), "avg": _rnd(sum(freqs)/len(freqs))}
                if volts:
                    dev_analysis["voltage_V"] = {"min": _rnd(min(volts)), "max": _rnd(max(volts)), "avg": _rnd(sum(volts)/len(volts))}

            # Alarm count for this device
            dev_alarms = [a for a in report["alarms_timeline"] if a.get("device_id") == did]
            dev_analysis["alarm_count"] = len(dev_alarms)
            dev_analysis["active_alarm_count"] = sum(1 for a in dev_alarms if a.get("is_active"))

            # Journal events (state transitions) for this device
            _jbd = report.get("_journal_by_device", {})
            dev_journal = _jbd.get(did, [])
            if dev_journal:
                dev_analysis["state_transitions"] = dev_journal[:30]  # Last 30 transitions
                # Summarize key transitions for quick overview
                gs_transitions = [j for j in dev_journal if j.get("category") == "GEN_STATUS"]
                mode_transitions = [j for j in dev_journal if j.get("category") == "MODE_CHANGE"]
                mains_events = [j for j in dev_journal if j.get("category") == "MAINS"]
                sys_events = [j for j in dev_journal if j.get("category") == "SYSTEM"]
                dev_analysis["transition_summary"] = {
                    "gen_status_changes": len(gs_transitions),
                    "mode_changes": len(mode_transitions),
                    "mains_events": len(mains_events),
                    "system_events": len(sys_events),
                    "total_journal_events": len(dev_journal),
                }

            # v4.0: Store raw history for trend analysis (will be cleaned up before return)
            dev_analysis["_raw_history"] = hist

            report["devices_analysis"].append(dev_analysis)

        # 4. Recalculate totals (nominal-based, proxy no longer needed)
        gen_analyses = [da for da in report["devices_analysis"] if da.get("type") == "генератор"]
        total_energy_lost_kwh = sum(da.get("estimated_lost_kwh", 0) for da in gen_analyses)
        total_downtime_minutes = sum(da.get("downtime_minutes", 0) for da in gen_analyses)

        # 4.5. Deep search: if generator has downtime but NO alarms, search ALL history
        for da in gen_analyses:
            did = da.get("device_id")
            dt_min = da.get("downtime_minutes", 0)
            dev_alarms = [a for a in report["alarms_timeline"] if a.get("device_id") == did]
            if dt_min > 60 and len(dev_alarms) == 0:
                # No alarms in analysis period — search entire alarm history for this device
                try:
                    deep_params = {"device_id": did, "limit": 100}
                    deep_alarms = await _api_get("/api/alarm-analytics/events", deep_params)
                    deep_entries = []
                    if isinstance(deep_alarms, list):
                        for a in deep_alarms:
                            if a.get("device_id") != did:
                                continue
                            occurred = a.get("occurred_at")
                            dev_info = dev_map.get(did, {})
                            _ds_sid = dev_info.get("site_id")
                            deep_entries.append({
                                "time": _utc_to_msk(occurred),
                                "time_utc": occurred,
                                "device_id": did,
                                "device_name": dev_info.get("name", f"#{did}"),
                                "site_id": _ds_sid,
                                "site_name": site_name_map.get(_ds_sid, "") if _ds_sid else "",
                                "alarm_code": a.get("alarm_code"),
                                "severity": a.get("alarm_severity") or a.get("severity"),
                                "message": a.get("alarm_name_ru") or a.get("alarm_name") or a.get("message"),
                                "is_active": a.get("is_active", False),
                                "deep_search": True,
                            })
                    if deep_entries:
                        da["deep_search_alarms"] = deep_entries[:15]
                        da["deep_search_note"] = (
                            f"За период анализа ({last_hours}ч) аварий не найдено. "
                            f"Полный поиск по истории: найдено {len(deep_entries)} аварий. "
                            f"Вероятная причина остановки — см. deep_search_alarms."
                        )
                        for de in deep_entries[:5]:
                            de["_deep_search"] = True
                            report["alarms_timeline"].append(de)
                        logger.info("Deep search for device %d: found %d alarms (full history)", did, len(deep_entries))
                    else:
                        da["deep_search_note"] = (
                            f"За период анализа ({last_hours}ч) и полный поиск по всей истории аварийных кодов не найдено. "
                            f"Вероятно плановый останов или ручной STOP. Аварийных кодов нет. Уточните у оператора."
                        )
                except Exception as e:
                    logger.warning("Deep alarm search failed for device %d: %s", did, e)

        # 5. Summary with plan vs actual
        total_alarms = len(report["alarms_timeline"])
        active_alarms = sum(1 for a in report["alarms_timeline"] if a.get("is_active"))
        shutdown_alarms = sum(1 for a in report["alarms_timeline"] if a.get("severity") == "shutdown")

        gen_count = len(gen_analyses)
        # Dynamic nominal: per-device from registry, fallback to avg running power
        plan_kwh = 0
        nominal_kw_avg = 0
        # Calculate site average running power as fallback for missing nominals
        _running_powers = [da.get("avg_running_power_kw", 0) for da in gen_analyses if da.get("avg_running_power_kw", 0) > 1]
        site_avg_running_kw = sum(_running_powers) / len(_running_powers) if _running_powers else 160.0

        for da in gen_analyses:
            did = da.get("device_id")
            nom = await _get_nominal_kw(did) if did else None
            if nom:
                da["nominal_kw"] = nom
            else:
                # Fallback: use avg_running_power if available, else site average
                nom = da.get("avg_running_power_kw") or site_avg_running_kw
                da["nominal_kw"] = nom
                da["nominal_source"] = "avg_running_power"
            # Use energy_period_hours (same period as energy delta) for accurate plan
            dev_span = da.get("energy_period_hours") or last_hours
            da["plan_kwh"] = round(nom * dev_span, 1)
            raw_energy = da.get("energy_kwh")
            da["actual_kwh"] = raw_energy if raw_energy is not None else 0
            da["energy_data_available"] = raw_energy is not None
            if da["plan_kwh"] > 0 and da["energy_data_available"]:
                da["utilization_pct"] = min(round(da["actual_kwh"] / da["plan_kwh"] * 100, 1), 120.0)
            else:
                da["utilization_pct"] = 0
            plan_kwh += da["plan_kwh"]
        plan_kwh = round(plan_kwh, 1)
        nominal_kw_avg = round(plan_kwh / (gen_count * last_hours), 1) if gen_count > 0 and last_hours > 0 else 0
        actual_kwh = sum(da.get("actual_kwh", 0) or 0 for da in gen_analyses)
        utilization_pct = round(actual_kwh / plan_kwh * 100, 1) if plan_kwh > 0 else 0

        report["summary"] = {
            "total_alarms": total_alarms,
            "active_alarms_now": active_alarms,
            "shutdown_alarms": shutdown_alarms,
            "total_downtime_minutes": round(total_downtime_minutes, 0),
            "total_downtime_hours": round(total_downtime_minutes / 60, 1),
            "estimated_energy_lost_kwh": round(total_energy_lost_kwh, 1),
            "devices_analyzed": len(report["devices_analysis"]),
            "generators_count": gen_count,
            "nominal_power_per_gen_kw": nominal_kw_avg,
            "avg_running_power_kw": site_avg_running_kw,
            "plan_energy_kwh": plan_kwh,
            "actual_energy_kwh": round(actual_kwh, 1),
            "utilization_pct": utilization_pct,
            "underproduction_kwh": round(plan_kwh - actual_kwh, 1) if plan_kwh > actual_kwh else 0,
        }

        # v4.0: Collect incident history for time pattern detection (30 days)
        try:
            hist_alarms = await _api_get("/api/alarm-analytics/events", {
                "site_id": site_id, "limit": 200,
            })
            if isinstance(hist_alarms, list) and len(hist_alarms) >= 2:
                incident_list = []
                for ha in hist_alarms:
                    ts_str = ha.get("occurred_at") or ha.get("started_at")
                    if not ts_str:
                        continue
                    try:
                        ts = datetime.fromisoformat(str(ts_str).replace("Z", "").replace("+00:00", ""))
                        _ha_did = ha.get("device_id")
                        _ha_dev = dev_map.get(_ha_did, {})
                        _ha_sid = _ha_dev.get("site_id")
                        incident_list.append({
                            "started_at": ts,
                            "alarm_code": ha.get("alarm_code", ""),
                            "device_id": _ha_did,
                            "device_name": _ha_dev.get("name", f"#{_ha_did}"),
                            "site_name": site_name_map.get(_ha_sid, "") if _ha_sid else "",
                        })
                    except Exception:
                        pass
                if incident_list:
                    report["incident_history"] = incident_list
        except Exception as e:
            logger.debug("Incident history collection failed: %s", e)

        # v4.0: Trend analysis for running generators
        try:
            all_trend_warnings = []
            for da in gen_analyses:
                if da.get("downtime_minutes", 0) < da.get("data_span_hours", 24) * 30:
                    # Generator was running at least part of the time — check trends
                    did = da.get("device_id")
                    hist_data = da.get("_raw_history", [])
                    if hist_data and len(hist_data) >= 10:
                        nom_dict = {}
                        nom_kw = da.get("nominal_kw")
                        if nom_kw:
                            nom_dict["coolant_temp_max"] = 95
                            nom_dict["oil_pressure_min"] = 150
                        tw = _analyze_trends(da.get("name", f"#{did}"), hist_data, nom_dict)
                        all_trend_warnings.extend(tw)
            if all_trend_warnings:
                report["trend_warnings"] = all_trend_warnings
        except Exception as e:
            logger.debug("Trend analysis failed: %s", e)

        # Cleanup internal temp data
        report.pop("_journal_by_device", None)
        # Remove raw history from report (used only for trends, don't send to LLM)
        for da in report.get("devices_analysis", []):
            da.pop("_raw_history", None)

    except Exception as e:
        logger.error("Error analyzing incident: %s", e, exc_info=True)
        report["error"] = str(e)

    return report


def _rnd(val, digits=1):
    """Round a value if it's a number, else return None."""
    if val is None:
        return None
    try:
        return round(float(val), digits)
    except (TypeError, ValueError):
        return None


async def _get_energy_delta(device_id: int, last_hours: int, is_generator: bool = True) -> dict:
    """Get energy_kwh and run_hours deltas using first/last points.

    Returns dict with energy_delta, rh_delta, actual_hours (or None).
    Tries shorter periods if no valid data at full range (old data may lack energy_kwh).
    """
    result = {"energy_delta": None, "rh_delta": None, "actual_hours": None}
    e_fields = "energy_kwh,run_hours" if is_generator else "energy_kwh"

    def _first_valid(pts, field):
        """Find first non-null positive value in a list of points."""
        if not isinstance(pts, list):
            return None
        for pt in pts:
            v = pt.get(field)
            if v is not None and v > 0:
                return v
        return None

    try:
        # Get latest point first
        last_pts = await _api_get(f"/api/history/metrics/{device_id}", {
            "last_minutes": 5, "fields": e_fields, "limit": 10,
        })
        rev_last = list(reversed(last_pts)) if isinstance(last_pts, list) else []
        e1 = _first_valid(rev_last, "energy_kwh")
        rh1 = _first_valid(rev_last, "run_hours") if is_generator else None

        if e1 is None:
            return result  # No energy data at all

        # v3.4 PERF: max 2 attempts (was 5 progressive fallbacks)
        periods = [last_hours] if last_hours <= 24 else [last_hours, 24]
        e0 = None
        rh0 = None
        actual_h = last_hours
        first_pts_found = None
        for try_h in periods:
            first_pts = await _api_get(f"/api/history/metrics/{device_id}", {
                "last_hours": try_h, "fields": e_fields, "limit": _dynamic_limit(try_h, base_per_hour=5, minimum=50, maximum=500),
            })
            e0 = _first_valid(first_pts, "energy_kwh")
            if is_generator:
                rh0 = _first_valid(first_pts, "run_hours")
            if e0 is not None:
                first_pts_found = first_pts
                actual_h = try_h
                break

        if e0 is not None and e1 >= e0:
            result["energy_delta"] = round(e1 - e0, 1)
            # Compute actual_hours from REAL timestamps, not query window
            try:
                _first_ts_str = None
                _last_ts_str = None
                if isinstance(first_pts_found, list):
                    for pt in first_pts_found:
                        if pt.get("energy_kwh") is not None and pt["energy_kwh"] > 0:
                            _first_ts_str = pt.get("timestamp")
                            break
                if isinstance(rev_last, list):
                    for pt in rev_last:
                        if pt.get("energy_kwh") is not None and pt["energy_kwh"] > 0:
                            _last_ts_str = pt.get("timestamp")
                            break
                if _first_ts_str and _last_ts_str:
                    _t0 = datetime.fromisoformat(str(_first_ts_str).replace("Z", "").replace("+00:00", ""))
                    _t1 = datetime.fromisoformat(str(_last_ts_str).replace("Z", "").replace("+00:00", ""))
                    _span = round((_t1 - _t0).total_seconds() / 3600, 1)
                    if _span > 0.5:  # at least 30 min span
                        actual_h = _span
            except Exception:
                pass  # keep try_h as fallback
            result["actual_hours"] = actual_h
        if rh0 is not None and rh1 is not None and rh1 >= rh0:
            result["rh_delta"] = round(rh1 - rh0, 1)
    except Exception as e:
        logger.warning("Energy delta calc failed for device %d: %s", device_id, e)
    return result


