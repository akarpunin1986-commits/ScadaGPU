    """Execute a SCADA tool and return result (with caching for read-only tools)."""
    # v4.1: Check cache for read-only tools
    if name in _CACHEABLE_TOOLS:
        cache_key = f"{name}:{json.dumps(args, sort_keys=True, default=str)}"
        if cache_key in _tool_cache:
            logger.debug("Tool cache hit: %s", name)
            return _tool_cache[cache_key]

    result = await _execute_tool_impl(name, args)

    # Cache read-only results
    if name in _CACHEABLE_TOOLS:
        _tool_cache[cache_key] = result

    return result


