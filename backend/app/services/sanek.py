class SanekAssistant:
    """
    AI assistant for SCADA operators.

    Usage:
        assistant = SanekAssistant(provider="openai", api_key="sk-...", model="gpt-4o")
        response = await assistant.chat(messages, pending_action=None)
    """

    def __init__(self, provider: str, api_key: str, model: str = "",
                 conv_id: str = ""):
        self.provider = provider
        self.api_key = api_key
        self.model = model or {
            "openai": "gpt-4o",
            "claude": "claude-sonnet-4-20250514",
            "gemini": "gemini-2.5-flash",
            "grok": "grok-3-mini",
        }.get(provider, "gpt-4o")
        self.timeout = settings.AI_TIMEOUT
        self.conv_id = conv_id  # for investigation context

    async def chat(
        self,
        messages: list[dict],
        pending_action: Optional[dict] = None,
    ) -> dict:
        """
        Process a chat turn with tool calling.

        Args:
            messages: Conversation history [{role, content}]
            pending_action: If set, user is confirming/declining a previous action.

        Returns:
            {
                "message": str,          # Assistant's text reply
                "actions": [...]          # Executed tool calls
                "pending_action": {...}   # If dangerous command needs confirmation
            }
        """
        # v4.1: Clear tool cache for this request
        _tool_cache_clear()
        # v4.2: Set conv_id for investigation tools
        _current_conv_id.set(self.conv_id)

        # Handle pending action confirmation
        if pending_action:
            # Find the last USER message (skip system context hints)
            last_msg = ""
            for m in reversed(messages):
                if m.get("role") == "user":
                    last_msg = m.get("content", "").strip().lower()
                    break
            # v4.1: flexible confirmation matching
            confirm_words = {"да", "yes", "подтверждаю", "ок", "ok", "давай", "выполняй", "делай", "go", "подтверди"}
            is_confirmed = any(w in last_msg for w in confirm_words)
            if is_confirmed:
                # Execute the confirmed action
                tool_name = pending_action["tool"]
                tool_args = pending_action["args"]
                logger.info("Executing confirmed action: %s(%s)", tool_name, tool_args)
                result = await execute_tool(tool_name, tool_args)
                return {
                    "message": f"✅ Выполнено: {pending_action.get('description', tool_name)}\n\nРезультат: {json.dumps(result, ensure_ascii=False, indent=2)[:500]}",
                    "actions": [{"tool": tool_name, "args": tool_args, "result": result}],
                    "pending_action": None,
                }
            else:
                return {
                    "message": "❌ Действие отменено.",
                    "actions": [],
                    "pending_action": None,
                }

        # Build messages with dynamic system prompt (sites/devices from DB)
        sites_section = await _build_sites_section()
        prompt = SANEK_SYSTEM_PROMPT_TEMPLATE.replace("{sites_section}", sites_section)
        full_messages = [{"role": "system", "content": prompt}] + messages

        # v3.0: Inject persistent memory (user instructions, facts, preferences)
        try:
            persistent_mem = await _load_memories(user_id=None)  # TODO: pass user_id when auth is added
            if persistent_mem:
                full_messages.insert(1, {"role": "system", "content": persistent_mem})
        except Exception as e:
            logger.warning("Persistent memory injection error: %s", e)

        # v3.0: Inject session memory (recent incidents from SanekAgent)
        try:
            memory = await _get_session_memory(self._extract_site_id(full_messages))
            if memory:
                full_messages.insert(len(full_messages) > 2 and 2 or 1, {"role": "system", "content": memory})
        except Exception as e:
            logger.warning("Memory injection error: %s", e)

        # v4.2: Inject investigation context (multi-turn reasoning)
        try:
            investigation = await _get_investigation(self.conv_id)
            if investigation:
                facts = "\n".join(f"- {f}" for f in investigation.get("key_facts", []))
                questions = "\n".join(f"- {q}" for q in investigation.get("open_questions", []))
                inv_ctx = (
                    f"[АКТИВНОЕ РАССЛЕДОВАНИЕ]\n"
                    f"Тема: {investigation.get('topic', '')}\n"
                    f"Установленные факты:\n{facts}\n"
                    f"Открытые вопросы:\n{questions}"
                )
                full_messages.insert(-1, {"role": "system", "content": inv_ctx})
        except Exception as e:
            logger.warning("Investigation context injection error: %s", e)

        # v3.2: Auto-learning — detect corrections and hint LLM to remember
        try:
            correction_hint = _detect_correction(messages)
            if correction_hint:
                logger.info("Correction detected, injecting auto-learn hint")
                full_messages.append({"role": "system", "content": correction_hint})
        except Exception as e:
            logger.warning("Correction detection error: %s", e)

        # Call LLM with tools
        if self.provider in ("openai", "grok"):
            result = await self._chat_openai(full_messages)
        elif self.provider == "claude":
            result = await self._chat_claude(full_messages)
        elif self.provider == "gemini":
            result = await self._chat_gemini(full_messages)
        else:
            return {"message": f"Неизвестный провайдер: {self.provider}", "actions": [], "pending_action": None}

        # v3.0: Strip fluff — remove generic phrases from LLM output
        if result and result.get("message"):
            result["message"] = _strip_fluff(result["message"])
            # Extract clarification buttons (explicit tags)
            clean_text, clarification = _extract_clarification(result["message"])
            if clarification:
                result["message"] = clean_text
                result["clarification"] = clarification
            else:
                # Fallback: detect text-based suggestions → convert to buttons
                clean_text, clarification = _extract_text_suggestions(result["message"])
                if clarification:
                    result["message"] = clean_text
                    result["clarification"] = clarification

        return result

    # ------------------------------------------------------------------
    # Two-tier streaming chat (SSE)
    # ------------------------------------------------------------------
    async def chat_stream(
        self,
        messages: list[dict],
        pending_action: Optional[dict] = None,
    ):
        """
        Async generator yielding SSE events for two-tier mode.
        Fast questions → quick response (no streaming).
        Deep analysis → streams tool-call progress.

        Yields dicts: {type: "mode"/"step"/"done"/"error", ...}
        """
        # v4.1: Clear tool cache for this request
        _tool_cache_clear()
        # v4.2: Set conv_id for investigation tools
        _current_conv_id.set(self.conv_id)

        # Handle pending action (no streaming needed)
        if pending_action:
            last_msg = ""
            for m in reversed(messages):
                if m.get("role") == "user":
                    last_msg = m.get("content", "").strip().lower()
                    break
            # v4.1: flexible confirmation matching
            confirm_words = {"да", "yes", "подтверждаю", "ок", "ok", "давай", "выполняй", "делай", "go", "подтверди"}
            is_confirmed = any(w in last_msg for w in confirm_words)
            if is_confirmed:
                tool_name = pending_action["tool"]
                tool_args = pending_action["args"]
                result = await execute_tool(tool_name, tool_args)
                yield {
                    "type": "done",
                    "message": f"✅ Выполнено: {pending_action.get('description', tool_name)}\n\nРезультат: {json.dumps(result, ensure_ascii=False, indent=2)[:500]}",
                    "actions": [{"tool": tool_name, "args": tool_args}],
                    "pending_action": None,
                }
            else:
                yield {"type": "done", "message": "❌ Действие отменено.", "actions": [], "pending_action": None}
            return

        # Determine mode: fast vs deep
        user_text = ""
        for m in reversed(messages):
            if m.get("role") == "user":
                user_text = m.get("content", "").lower()
                break

        has_deep = any(kw in user_text for kw in DEEP_KEYWORDS)
        has_fast = any(kw in user_text for kw in FAST_KEYWORDS)
        # FAST_KEYWORDS принудительно включают fast mode, если нет DEEP_KEYWORDS
        if has_fast and not has_deep:
            is_deep = False
        else:
            is_deep = has_deep
        yield {"type": "mode", "mode": "deep" if is_deep else "fast"}

        # Build messages with appropriate prompt (dynamic sites/devices from DB)
        sites_section = await _build_sites_section()
        template = SANEK_SYSTEM_PROMPT_TEMPLATE if is_deep else SANEK_FAST_PROMPT_TEMPLATE
        prompt = template.replace("{sites_section}", sites_section)
        full_messages = [{"role": "system", "content": prompt}] + messages

        # Inject memories (deep mode only — fast stays lean)
        if is_deep:
            try:
                persistent_mem = await _load_memories(user_id=None)
                if persistent_mem:
                    full_messages.insert(1, {"role": "system", "content": persistent_mem})
            except Exception:
                pass
            try:
                memory = await _get_session_memory(self._extract_site_id(full_messages))
                if memory:
                    full_messages.insert(2, {"role": "system", "content": memory})
            except Exception:
                pass

        # v4.2: Inject investigation context (multi-turn reasoning)
        if is_deep:
            try:
                investigation = await _get_investigation(self.conv_id)
                if investigation:
                    facts = "\n".join(f"- {f}" for f in investigation.get("key_facts", []))
                    questions = "\n".join(f"- {q}" for q in investigation.get("open_questions", []))
                    inv_ctx = (
                        f"[АКТИВНОЕ РАССЛЕДОВАНИЕ]\n"
                        f"Тема: {investigation.get('topic', '')}\n"
                        f"Установленные факты:\n{facts}\n"
                        f"Открытые вопросы:\n{questions}"
                    )
                    full_messages.insert(-1, {"role": "system", "content": inv_ctx})
            except Exception as e:
                logger.warning("Investigation context injection error: %s", e)

        # v3.2: Auto-learning — detect corrections (both fast and deep)
        try:
            correction_hint = _detect_correction(messages)
            if correction_hint:
                logger.info("Correction detected in stream, injecting auto-learn hint")
                full_messages.append({"role": "system", "content": correction_hint})
        except Exception:
            pass

        # Select provider method
        progress_queue = asyncio.Queue() if is_deep else None
        fast_only = not is_deep

        async def _run():
            if self.provider in ("openai", "grok"):
                return await self._chat_openai(full_messages, fast_only=fast_only, progress_queue=progress_queue)
            elif self.provider == "claude":
                return await self._chat_claude(full_messages, fast_only=fast_only, progress_queue=progress_queue)
            elif self.provider == "gemini":
                return await self._chat_gemini(full_messages, fast_only=fast_only, progress_queue=progress_queue)
            else:
                return {"message": f"Неизвестный провайдер: {self.provider}", "actions": [], "pending_action": None}

        if is_deep:
            # Deep mode: run LLM in background task, stream progress
            task = asyncio.create_task(_run())
            try:
                while not task.done():
                    try:
                        event = await asyncio.wait_for(progress_queue.get(), timeout=1.0)
                        yield event
                    except asyncio.TimeoutError:
                        continue
                # Drain remaining events
                while not progress_queue.empty():
                    event = progress_queue.get_nowait()
                    yield event
                result = task.result()
            except Exception as e:
                logger.error("chat_stream deep error: %s", e, exc_info=True)
                yield {"type": "error", "message": str(e)}
                return
        else:
            # Fast mode: just await directly
            try:
                result = await _run()
            except Exception as e:
                logger.error("chat_stream fast error: %s", e, exc_info=True)
                yield {"type": "error", "message": str(e)}
                return

            # v4.2: Auto-escalate fast→deep if LLM self-limits
            _SELF_LIMIT_PHRASES = [
                "не могу получить", "не посчитать", "инструмент не",
                "нет данных", "нет доступа", "ограничен", "не поддерживает",
                "не удалось получить", "данные отсутствуют в текущем",
                "средние за 24 часа, без часов", "инструмент снова вернул",
            ]
            msg_lower = (result.get("message") or "").lower()
            if any(p in msg_lower for p in _SELF_LIMIT_PHRASES):
                logger.info("Fast mode self-limited, auto-escalating to deep mode")
                yield {"type": "mode", "mode": "deep (auto-escalation)"}
                # Rebuild with full prompt and all tools
                _tool_cache_clear()
                full_prompt = SANEK_SYSTEM_PROMPT_TEMPLATE.replace("{sites_section}", sites_section)
                deep_messages = [{"role": "system", "content": full_prompt}] + messages
                try:
                    if self.provider in ("openai", "grok"):
                        result = await self._chat_openai(deep_messages, fast_only=False)
                    elif self.provider == "claude":
                        result = await self._chat_claude(deep_messages, fast_only=False)
                    elif self.provider == "gemini":
                        result = await self._chat_gemini(deep_messages, fast_only=False)
                except Exception as e:
                    logger.error("Auto-escalation deep error: %s", e, exc_info=True)
                    # Keep the fast mode result if deep fails

        # Strip fluff
        if result and result.get("message"):
            result["message"] = _strip_fluff(result["message"])

        # Extract clarification buttons if present
        done_event = {
            "type": "done",
            "message": result.get("message", ""),
            "actions": [{"tool": a["tool"], "args": a.get("args", {})} for a in result.get("actions", [])],
            "pending_action": result.get("pending_action"),
        }
        if done_event["message"]:
            clean_text, clarification = _extract_clarification(done_event["message"])
            if clarification:
                done_event["message"] = clean_text
                done_event["clarification"] = clarification
            else:
                # Fallback: detect text-based suggestions → convert to buttons
                clean_text, clarification = _extract_text_suggestions(done_event["message"])
                if clarification:
                    done_event["message"] = clean_text
                    done_event["clarification"] = clarification

        yield done_event

